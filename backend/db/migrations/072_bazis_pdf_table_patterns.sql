-- 072_bazis_pdf_table_patterns.sql
-- Reusable structural mappings for Basis PDF tables.
-- Never stores PDF bytes, filenames, hashes, raw rows, or document values.
BEGIN;

CREATE TABLE IF NOT EXISTS bazis_pdf_table_patterns (
  bazis_pdf_table_pattern_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint                VARCHAR(64) NOT NULL,
  fingerprint_version        SMALLINT NOT NULL,
  parser_major               SMALLINT NOT NULL,
  signature_json             JSONB NOT NULL,
  mapping_json               JSONB NOT NULL,
  mapping_hash               VARCHAR(64) NOT NULL,
  approval_status            VARCHAR(16) NOT NULL DEFAULT 'pending',
  is_active                  BOOLEAN NOT NULL DEFAULT true,
  version                    INTEGER NOT NULL DEFAULT 1,
  learned_by                 BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  edited_by                  BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_bazis_pdf_table_patterns_fingerprint
    UNIQUE (fingerprint_version, parser_major, fingerprint),
  CONSTRAINT chk_bazis_pdf_table_patterns_fingerprint
    CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  CONSTRAINT chk_bazis_pdf_table_patterns_signature
    CHECK (jsonb_typeof(signature_json) = 'object'),
  CONSTRAINT chk_bazis_pdf_table_patterns_mapping
    CHECK (jsonb_typeof(mapping_json) = 'object'),
  CONSTRAINT chk_bazis_pdf_table_patterns_approval
    CHECK (approval_status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT chk_bazis_pdf_table_patterns_version CHECK (version >= 1)
);

CREATE INDEX IF NOT EXISTS idx_bazis_pdf_table_patterns_active
  ON bazis_pdf_table_patterns (fingerprint_version, parser_major, fingerprint)
  WHERE is_active;

COMMIT;
