-- 119_cnc_manual_svg_comment_presets.sql
-- User-maintained presets for comments on manual SVG cut uploads.

BEGIN;

CREATE TABLE IF NOT EXISTS cnc_manual_svg_comment_presets (
  preset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  comment_text TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'custom',
  is_active BOOLEAN NOT NULL DEFAULT true,
  sort_order INTEGER NOT NULL DEFAULT 500,
  version INTEGER NOT NULL DEFAULT 1,
  created_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_cnc_manual_svg_comment_presets_label
    CHECK (length(trim(label)) > 0 AND length(label) <= 120),
  CONSTRAINT chk_cnc_manual_svg_comment_presets_comment
    CHECK (length(trim(comment_text)) > 0 AND length(comment_text) <= 500),
  CONSTRAINT chk_cnc_manual_svg_comment_presets_category
    CHECK (category IN ('general', 'order', 'tool', 'material', 'rework', 'custom')),
  CONSTRAINT chk_cnc_manual_svg_comment_presets_sort_order
    CHECK (sort_order >= 0 AND sort_order <= 100000),
  CONSTRAINT chk_cnc_manual_svg_comment_presets_version
    CHECK (version > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_cnc_manual_svg_comment_presets_active_text
  ON cnc_manual_svg_comment_presets (lower(trim(comment_text)))
  WHERE is_active = true;

CREATE INDEX IF NOT EXISTS idx_cnc_manual_svg_comment_presets_active_order
  ON cnc_manual_svg_comment_presets (is_active, category, sort_order, label);

INSERT INTO cnc_manual_svg_comment_presets (label, comment_text, category, sort_order)
VALUES
  ('Весь заказ', 'весь заказ', 'order', 10),
  ('Фрезы', 'фрезы:', 'tool', 20),
  ('Материал', 'материал:', 'material', 30),
  ('Переделка', 'переделка', 'rework', 40),
  ('Срочно', 'срочно', 'general', 50)
ON CONFLICT DO NOTHING;

COMMIT;
