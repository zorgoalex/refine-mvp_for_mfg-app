import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { Client } from 'pg';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

const migration = (name: string) => readFileSync(new URL(name,import.meta.url),'utf8');
describe.skipIf(process.env.MDF_ENGINE_INTEGRATION !== '1')('typed cut result identity migration',()=>{
  const schema=`e2e_hdf_projection_${randomUUID().replaceAll('-','')}`;
  const db=new Client({host:process.env.PG_TAILSCALE_BIND_IP || process.env.PG_BIND_IP || '127.0.0.1',
    database:process.env.PG_DB,user:process.env.PG_USER,password:process.env.PG_PASSWORD,connectionTimeoutMillis:5000,
    options:'-c statement_timeout=15000 -c lock_timeout=3000 -c max_parallel_workers_per_gather=0 -c jit=off'});
  const sql=()=>migration('177_cut_result_typed_hdf.sql');
  let legacyId:string;
  beforeAll(async()=>{
    await db.connect(); await db.query(`CREATE SCHEMA ${schema}; SET search_path=${schema},public;
      CREATE TABLE users(user_id bigint PRIMARY KEY,username text);
      CREATE TABLE cut_job(cut_job_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text);
      CREATE TABLE order_label_generations(order_label_generation_id bigint PRIMARY KEY);
      CREATE TABLE label_template_elements(kind text);`);
    for(const name of ['079_cut_result_history_expand.sql','080_cut_result_history_finalize.sql','081_label_cut_maps.sql',
      '085_cut_result_manual_revisions.sql','121_cut_result_informational_snapshots.sql','122_cut_result_informational_label_maps.sql',
      '153_svg_partial_label_maps.sql','154_svg_source_instance_sequences.sql']) await db.query(migration(name));
    legacyId=await save(snapshot([{orderDetailId:7,orderId:1,qty:1,cutGroupId:20}],['det-7']));
    await db.query(sql());
  });
  afterAll(async()=>{
    try { await db.query(`ROLLBACK; SET search_path=public; DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      expect((await db.query('SELECT 1 FROM pg_namespace WHERE nspname=$1',[schema])).rows).toHaveLength(0);
    } finally { await db.end(); }
  });
  function item(kind:'det'|'hdf',id=7) {
    return {sourceType:kind==='hdf'?'order_hdf_detail':'order_detail',itemId:`${kind}-${id}`,
      orderDetailId:id,orderHdfDetailId:kind==='hdf'?id:null,orderId:1,qty:1,cutGroupId:20};
  }
  function snapshot(items:Record<string,unknown>[],ids:string[]) {
    const sheet={sheetIndex:0,placements:{sheet_width_mm:1000,sheet_height_mm:1000,trim_mm:{left:0,top:0},
      pieces:ids.map((id,i)=>({item_id:id,instance:1,x_mm:i*100,y_mm:0,width_mm:90,height_mm:90,rotated:false,
        label:{orderId:null,detailId:null}}))},
      renderSnapshot:{contractVersion:'cut_sheet_render_v1',pdfMeta:{},pdfDetailRows:[],
        views:Object.fromEntries(['r0:raw:top-left:labels-off',...Array.from({length:11},(_,i)=>`view-${i}`)].map(k=>[k,{svg:'<svg/>'}]))}};
    return {items,groups:[{cutGroupId:20,sheets:[sheet],manualLayout:null as null|{sheets:typeof sheet[];isActive:boolean;isStale:boolean}}],
      totals:{},unplaced:[] as {itemId:string;instance:number}[]};
  }
  const valid=async(s:ReturnType<typeof snapshot>)=>(await db.query(`SELECT cut_result_snapshot_is_complete(
    $1::jsonb,cut_result_expected_manifest($1::jsonb),cut_result_snapshot_digest($1::jsonb)) valid`,[JSON.stringify(s)])).rows[0].valid;
  async function save(s:ReturnType<typeof snapshot>) {
    const id=(await db.query("INSERT INTO cut_job(name) VALUES('E2E typed projection') RETURNING cut_job_id")).rows[0].cut_job_id;
    const stored={...s,cutJobId:Number(id)};
    return (await db.query(`INSERT INTO cut_result(cut_job_id,result_no,result_kind,source_job_version,
      snapshot_job,snapshot_manifest,snapshot_digest,totals_snapshot)
      VALUES($1,1,'legacy',1,$2::jsonb,cut_result_expected_manifest($2::jsonb),cut_result_snapshot_digest($2::jsonb),'{}')
      RETURNING cut_result_id`,[id,JSON.stringify(stored)])).rows[0].cut_result_id as string;
  }
  const placements=async(id:string)=>(await db.query(`SELECT item_id,order_detail_id,order_hdf_detail_id,variant
    FROM cut_result_placement WHERE cut_result_id=$1 ORDER BY variant,item_id`,[id])).rows;
  it('preserves old det projection and is rerunnable without rewriting archive rows',async()=>{
    const before=await placements(legacyId);
    await db.query(sql()); await db.query('SELECT project_cut_result_label_maps($1)',[legacyId]);
    expect(await placements(legacyId)).toEqual(before);
    expect(before).toEqual([{item_id:'det-7',order_detail_id:'7',order_hdf_detail_id:null,variant:'auto'}]);
  });
  it.each(['auto','active','inactive','stale'] as const)('keeps colliding det/HDF numeric identities distinct for %s layout',async state=>{
    const s=snapshot([item('det'),item('hdf')],['det-7','hdf-7']);
    if(state!=='auto') s.groups[0].manualLayout={sheets:structuredClone(s.groups[0].sheets),isActive:state==='active',isStale:state==='stale'};
    expect(await valid(s)).toBe(true); const id=await save(s),rows=await placements(id);
    expect(rows).toHaveLength(state==='auto'?2:4);
    for(const row of rows) expect(row).toMatchObject(row.item_id==='hdf-7'
      ? {order_detail_id:null,order_hdf_detail_id:'7'} : {order_detail_id:'7',order_hdf_detail_id:null});
    const effective=(await db.query('SELECT variant FROM cut_result_sheet_map WHERE cut_result_id=$1 AND is_effective',[id])).rows;
    expect(effective).toEqual([{variant:state==='active'?'manual':'auto'}]);
  });
  it('accepts typed HDF without compatibility alias and sparse placed instances with unplaced remainder',async()=>{
    const s=snapshot([{...item('hdf'),orderDetailId:null,qty:2}],['hdf-7']);
    s.groups[0].sheets[0].placements.pieces[0].instance=2;s.unplaced=[{itemId:'hdf-7',instance:1}];
    expect(await valid(s)).toBe(true);expect(await placements(await save(s))).toHaveLength(1);
  });
  it.each([
    {sourceType:'unknown'}, {sourceType:null}, {orderHdfDetailId:null}, {orderHdfDetailId:-1},
    {orderHdfDetailId:1.5}, {orderHdfDetailId:'7'}, {orderDetailId:8}, {itemId:'det-7'},
    {sourceType:'order_detail'}, {sourceType:undefined}, {orderId:null}, {itemId:undefined},
    {orderDetailId:'7'}, {orderHdfDetailId:1e30},
  ])('rejects forged HDF identity %j',async patch=>{
    const s=snapshot([{...item('hdf'),...patch}],['hdf-7']);
    expect(await valid(s)).toBe(false);await expect(save(s)).rejects.toThrow();
  });
  it('rejects duplicate definitions and unknown placements atomically',async()=>{
    for(const s of [snapshot([item('hdf'),item('hdf')],['hdf-7']),snapshot([item('hdf')],['hdf-8'])]) {
      const before=(await db.query('SELECT count(*) n FROM cut_result_placement')).rows[0].n;
      expect(await valid(s)).toBe(false);await expect(save(s)).rejects.toThrow();
      expect((await db.query('SELECT count(*) n FROM cut_result_placement')).rows[0].n).toBe(before);
    }
  });
  it('preserves mixed and informational SVG source-only geometry',async()=>{
    for(const s of [snapshot([],['svg-unresolved']),snapshot([item('hdf')],['hdf-7','svg-unresolved'])]) {
      expect(await valid(s)).toBe(true);
      expect((await placements(await save(s))).find(r=>r.item_id==='svg-unresolved'))
        .toMatchObject({order_detail_id:null,order_hdf_detail_id:null});
    }
  });
  it('keeps append-only and projection-only guards, exact replay and digest checks',async()=>{
    const s=snapshot([item('hdf')],['hdf-7']),id=await save(s),before=await placements(id);
    await db.query('SELECT project_cut_result_label_maps($1)',[id]);expect(await placements(id)).toEqual(before);
    await expect(db.query('UPDATE cut_result_placement SET order_hdf_detail_id=9 WHERE cut_result_id=$1',[id])).rejects.toThrow(/append-only/);
    await expect(db.query('DELETE FROM cut_result_placement WHERE cut_result_id=$1',[id])).rejects.toThrow(/append-only/);
    await expect(db.query('INSERT INTO cut_result_placement(cut_result_id) VALUES($1)',[id])).rejects.toThrow(/only by the projection/);
    expect((await db.query(`SELECT cut_result_snapshot_is_complete($1::jsonb,cut_result_expected_manifest($1::jsonb),repeat('0',64)) valid`,
      [JSON.stringify(s)])).rows[0].valid).toBe(false);
  });
  it('typed placement constraint rejects ambiguous or missing source identity',async()=>{
    const id=await save(snapshot([item('hdf')],['hdf-7']));
    for(const patch of [{order_detail_id:7},{order_hdf_detail_id:null},{item_id:'det-7'},
      {order_hdf_detail_id:-7},{order_id:null}]) {
      await db.query('BEGIN');
      try {
        await db.query("SELECT set_config('erp.cut_label_projection_result_id',$1,true)",[id]);
        await expect(db.query(`INSERT INTO cut_result_placement SELECT
          (jsonb_populate_record(NULL::cut_result_placement,to_jsonb(p) || $2::jsonb)).*
          FROM cut_result_placement p WHERE cut_result_id=$1`,[id,JSON.stringify({cut_result_placement_id:999999,instance:2,...patch})]))
          .rejects.toMatchObject({code:'23514',constraint:'chk_cut_result_placement_source_only_order'});
      } finally { await db.query('ROLLBACK'); }
    }
  });
});
