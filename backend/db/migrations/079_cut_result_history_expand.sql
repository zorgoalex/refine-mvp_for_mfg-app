-- 079_cut_result_history_expand.sql
--
-- Expand phase for immutable, per-job cut result history. Runtime writes remain
-- disabled during expand/backfill/finalize rollout. Snapshot columns are
-- intentionally nullable until the application backfill has rendered every
-- legacy current layout.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE OR REPLACE FUNCTION cut_result_snapshot_digest(p_snapshot JSONB)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE
AS $$
  SELECT encode(digest(p_snapshot::text, 'sha256'), 'hex')
$$;

CREATE TABLE IF NOT EXISTS cut_result (
  cut_result_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  cut_job_id             BIGINT NOT NULL,
  result_no              INTEGER NOT NULL,
  result_kind            TEXT NOT NULL,
  source_job_version     INTEGER NOT NULL,
  based_on_result_id     BIGINT,
  command_id             UUID,
  command_payload_hash   TEXT,
  request_hash           TEXT,
  snapshot_job           JSONB,
  snapshot_manifest      JSONB,
  snapshot_digest        TEXT,
  totals_snapshot        JSONB,
  created_by             BIGINT,
  created_by_name_snapshot TEXT,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT pk_cut_result PRIMARY KEY (cut_result_id),
  CONSTRAINT uq_cut_result_job_no UNIQUE (cut_job_id, result_no),
  CONSTRAINT uq_cut_result_job_id UNIQUE (cut_job_id, cut_result_id),
  CONSTRAINT uq_cut_result_job_command UNIQUE (cut_job_id, command_id),
  CONSTRAINT chk_cut_result_no CHECK (result_no > 0),
  CONSTRAINT chk_cut_result_kind CHECK (result_kind IN ('auto', 'manual', 'legacy')),
  CONSTRAINT fk_cut_result_job
    FOREIGN KEY (cut_job_id) REFERENCES cut_job(cut_job_id) ON DELETE RESTRICT,
  CONSTRAINT fk_cut_result_creator
    FOREIGN KEY (created_by) REFERENCES users(user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_cut_result_job_created
  ON cut_result (cut_job_id, result_no DESC);

ALTER TABLE cut_result
  ADD CONSTRAINT fk_cut_result_based_on_same_job
  FOREIGN KEY (cut_job_id, based_on_result_id)
  REFERENCES cut_result(cut_job_id, cut_result_id)
  DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE cut_job
  ADD COLUMN IF NOT EXISTS current_cut_result_id BIGINT,
  ADD COLUMN IF NOT EXISTS next_cut_result_no INTEGER NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS cut_result_command (
  cut_job_id           BIGINT NOT NULL,
  command_id           UUID NOT NULL,
  command_type         TEXT NOT NULL,
  payload_hash         TEXT NOT NULL,
  status               TEXT NOT NULL,
  cut_result_id        BIGINT,
  failure_code         TEXT,
  owner_token          UUID,
  lease_expires_at     TIMESTAMPTZ,
  heartbeat_at         TIMESTAMPTZ,
  claimed_job_version  INTEGER,
  attempt_no           INTEGER NOT NULL DEFAULT 1,
  created_by           BIGINT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at         TIMESTAMPTZ,
  CONSTRAINT pk_cut_result_command PRIMARY KEY (cut_job_id, command_id),
  CONSTRAINT uq_cut_result_command_payload
    UNIQUE (cut_job_id, command_id, payload_hash),
  CONSTRAINT chk_cut_result_command_type
    CHECK (command_type IN ('calculate', 'manual_save')),
  CONSTRAINT chk_cut_result_command_status
    CHECK (status IN ('in_progress', 'completed', 'failed')),
  CONSTRAINT fk_cut_result_command_job
    FOREIGN KEY (cut_job_id) REFERENCES cut_job(cut_job_id) ON DELETE RESTRICT,
  CONSTRAINT fk_cut_result_command_creator
    FOREIGN KEY (created_by) REFERENCES users(user_id) ON DELETE SET NULL,
  CONSTRAINT fk_cut_result_command_result_same_job
    FOREIGN KEY (cut_job_id, cut_result_id)
    REFERENCES cut_result(cut_job_id, cut_result_id)
    DEFERRABLE INITIALLY DEFERRED
);

ALTER TABLE cut_result
  ADD CONSTRAINT fk_cut_result_command_payload
  FOREIGN KEY (cut_job_id, command_id, command_payload_hash)
  REFERENCES cut_result_command(cut_job_id, command_id, payload_hash)
  DEFERRABLE INITIALLY DEFERRED;

COMMIT;
