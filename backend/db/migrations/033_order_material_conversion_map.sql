-- 033: committed conversion manifest (idempotent). Extend ONLY by a reviewed commit
-- to THIS file; prove zero-unmapped on the restore rehearsal BEFORE go-live. NEVER
-- edit the map during the cutover window. The manifest carries the FULL target-type
-- attributes (Critic R10 B2) — unit_id/material_type_id/dims/thickness — so 034 creates
-- each target type with the CORRECT attrs (not hardcoded), matching the SP3 contract:
--   не определён: mtype 3, 16мм; черновой МДФ 16мм: mtype 1, 16мм; МДФ 10мм: mtype 1,
--   10мм; ФАНЕРА: mtype 3, 18мм. Non-cuttable types use placeholder dims=1.
CREATE TABLE IF NOT EXISTS sheet_material_conversion_map (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_material_id   BIGINT,
  legacy_material_name TEXT,
  target_key           TEXT     NOT NULL,   -- IMMUTABLE identity of the target sheet type (Critic R22 B1)
  target_sheet_name    TEXT     NOT NULL,   -- DISPLAY name (operator-editable; NOT used as rerun identity)
  is_cuttable          BOOLEAN  NOT NULL DEFAULT true,
  target_unit_id          SMALLINT NOT NULL DEFAULT 1,
  target_material_type_id SMALLINT NOT NULL,
  target_width_mm         NUMERIC  NOT NULL,
  target_height_mm        NUMERIC  NOT NULL,
  target_thickness_mm     NUMERIC  NOT NULL,
  CONSTRAINT chk_map_key  CHECK (legacy_material_id IS NOT NULL OR legacy_material_name IS NOT NULL),
  CONSTRAINT chk_map_dims CHECK (target_width_mm > 0 AND target_height_mm > 0 AND target_thickness_mm > 0),
  CONSTRAINT uq_map_id    UNIQUE (legacy_material_id),
  CONSTRAINT uq_map_name  UNIQUE (legacy_material_name)
);
-- Critic R22 B1: add an immutable conversion key to sheet_material_types so 034
-- joins/creates targets by a STABLE key, not the mutable display name.
ALTER TABLE sheet_material_types
  ADD COLUMN IF NOT EXISTS conversion_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_sheet_material_types_conversion_key
  ON sheet_material_types(conversion_key) WHERE conversion_key IS NOT NULL;

