-- A target_key must have ONE consistent attr set across rows — assert below.
DO $$
DECLARE v_dup INT;
BEGIN
  SELECT count(*) INTO v_dup FROM (
    SELECT target_key FROM sheet_material_conversion_map
    GROUP BY target_key
    HAVING count(DISTINCT (target_sheet_name, is_cuttable, target_unit_id, target_material_type_id, target_width_mm, target_height_mm, target_thickness_mm)) > 1
  ) q;
  IF v_dup > 0 THEN RAISE EXCEPTION 'manifest: % target_key(s) have inconsistent attrs', v_dup; END IF;
END $$;

-- PREP sheet_material_types in 033 (Critic R27 B2/B3): add is_cuttable, adopt conversion_key
-- on any pre-existing target type BY NAME ONCE, create missing target types BY key, and set
-- is_cuttable — so that AFTER 033 (i.e. at PREFLIGHT time, before 034) every target is keyed
-- + cuttability-flagged and the preflight can resolve by conversion_key (not mutable name).
ALTER TABLE sheet_material_types ADD COLUMN IF NOT EXISTS is_cuttable BOOLEAN NOT NULL DEFAULT true;
UPDATE sheet_material_types s SET conversion_key = mk.target_key
  FROM (SELECT DISTINCT target_key, target_sheet_name FROM sheet_material_conversion_map) mk
 WHERE s.conversion_key IS NULL AND s.name = mk.target_sheet_name;
INSERT INTO sheet_material_types (name, unit_id, material_type_id, width_mm, height_mm, thickness_mm, is_active, is_cuttable, conversion_key)
SELECT DISTINCT ON (t.target_key) t.target_sheet_name, t.target_unit_id, t.target_material_type_id,
       t.target_width_mm, t.target_height_mm, t.target_thickness_mm, true, t.is_cuttable, t.target_key
FROM sheet_material_conversion_map t
WHERE NOT EXISTS (SELECT 1 FROM sheet_material_types s WHERE s.conversion_key = t.target_key)
ORDER BY t.target_key;
-- Reconcile EXISTING target rows to manifest-owned STRUCTURAL attrs (Critic R7 B1): if 033
-- is reapplied after a manifest edit, already-keyed types must be updated so that 034's
-- structural-attr fail-closed check (0.0b2) converges instead of aborting. DISPLAY attrs
-- (name, dims) are intentionally NOT overwritten — they are operator-editable via the SP1
-- UI and 034 does NOT assert them. Only manifest-owned structural attrs are reconciled:
-- unit_id, material_type_id, is_cuttable.
UPDATE sheet_material_types s
   SET unit_id           = mk.target_unit_id,
       material_type_id  = mk.target_material_type_id,
       is_cuttable       = mk.is_cuttable
  FROM (
    SELECT DISTINCT ON (target_key) target_key, target_unit_id, target_material_type_id, is_cuttable
    FROM sheet_material_conversion_map
    ORDER BY target_key
  ) mk
 WHERE s.conversion_key = mk.target_key
   AND (s.unit_id <> mk.target_unit_id
     OR s.material_type_id <> mk.target_material_type_id
     OR s.is_cuttable <> mk.is_cuttable);
