-- Access groups, stage 1 (migration M2): groups of fine-grained permissions and scopes, and the effective
-- authorization as base role ∪ active groups of the user while permissions_state.access_groups_enabled is on.
-- Plan: spec_erp/plans/access-groups/2026-10-29-access-groups-plan-v6.md (R7, §3).
--
-- Additive. The three objects of migration 248 are replaced with the SAME columns and signature; while the switch
-- is off (it is, and nothing here turns it on) every one of them returns exactly what 248 returns. Consumers keep
-- working unchanged: Hasura `_exists` predicates (stage 0B) and backend SQL read user_effective_permissions /
-- user_effective_scopes, the TypeScript loaders call user_authorization_snapshot.
--
-- * access_groups — a group (code, name, activity, version for compare-and-swap of the group and its members).
-- * access_group_permissions — catalog permissions of a group.
-- * access_group_scopes — scope values of a group; a SET per key (own and assigned together are allowed), only the
--   pairs of policy_scope_allowed_values, never 'none'.
-- * user_access_groups — membership.
-- A group adds rights only while it is active, the permission is active in the catalog, the user is active and the
-- switch is on. Groups never create Hasura permissions: the Hasura role stays the base role (plan §6).
BEGIN;

SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS public.access_groups (
  group_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  description text,
  is_active boolean NOT NULL DEFAULT true,
  version bigint NOT NULL DEFAULT 1,
  created_by bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_by bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT access_groups_code_key UNIQUE (code),
  CONSTRAINT access_groups_code_check CHECK (code ~ '^[a-z][a-z0-9_]{1,40}$'),
  CONSTRAINT access_groups_name_check CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT access_groups_version_check CHECK (version >= 1)
);

CREATE TABLE IF NOT EXISTS public.access_group_permissions (
  group_id bigint NOT NULL REFERENCES public.access_groups(group_id) ON DELETE CASCADE,
  permission_name text NOT NULL REFERENCES public.permissions_catalog(permission_name),
  PRIMARY KEY (group_id, permission_name)
);

CREATE TABLE IF NOT EXISTS public.access_group_scopes (
  group_id bigint NOT NULL REFERENCES public.access_groups(group_id) ON DELETE CASCADE,
  scope_key text NOT NULL,
  scope_value text NOT NULL,
  PRIMARY KEY (group_id, scope_key, scope_value),
  CONSTRAINT access_group_scopes_allowed_fkey FOREIGN KEY (scope_key, scope_value)
    REFERENCES public.policy_scope_allowed_values(scope_key, scope_value)
);

CREATE TABLE IF NOT EXISTS public.user_access_groups (
  user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  group_id bigint NOT NULL REFERENCES public.access_groups(group_id) ON DELETE CASCADE,
  added_by bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
  added_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, group_id)
);

-- Hasura predicates look up (user_id, permission_name) on every row: the group branch goes
-- user_access_groups (pk user_id, group_id) → access_group_permissions (pk group_id, permission_name).
CREATE INDEX IF NOT EXISTS user_access_groups_group_idx ON public.user_access_groups (group_id);
CREATE INDEX IF NOT EXISTS access_group_permissions_permission_idx ON public.access_group_permissions (permission_name);

-- Effective permissions: base role (as 248) ∪ active groups while the switch is on. UNION de-duplicates; the role
-- branch alone has no duplicates (role_permissions pk), so with the switch off the rows equal 248.
CREATE OR REPLACE VIEW public.user_effective_permissions AS
SELECT u.user_id, rp.permission_name
FROM public.users u
JOIN public.role_permissions rp ON rp.role_id = u.role_id AND rp.is_enabled
JOIN public.permissions_catalog pc ON pc.permission_name = rp.permission_name AND pc.is_active
WHERE u.is_active
UNION
SELECT u.user_id, agp.permission_name
FROM public.users u
JOIN public.user_access_groups uag ON uag.user_id = u.user_id
JOIN public.access_groups ag ON ag.group_id = uag.group_id AND ag.is_active
JOIN public.access_group_permissions agp ON agp.group_id = ag.group_id
JOIN public.permissions_catalog pc ON pc.permission_name = agp.permission_name AND pc.is_active
JOIN public.permissions_state ps ON ps.id AND ps.access_groups_enabled
WHERE u.is_active;

-- Effective scopes as rows: role (as 248, never 'none') ∪ active groups while the switch is on.
CREATE OR REPLACE VIEW public.user_effective_scopes AS
SELECT u.user_id, rps.scope_key, rps.scope_value
FROM public.users u
JOIN public.role_policy_scopes rps ON rps.role_id = u.role_id
WHERE u.is_active
  AND rps.scope_value <> 'none'
UNION
SELECT u.user_id, ags.scope_key, ags.scope_value
FROM public.users u
JOIN public.user_access_groups uag ON uag.user_id = u.user_id
JOIN public.access_groups ag ON ag.group_id = uag.group_id AND ag.is_active
JOIN public.access_group_scopes ags ON ags.group_id = ag.group_id
JOIN public.permissions_state ps ON ps.id AND ps.access_groups_enabled
WHERE u.is_active;

-- One-statement snapshot (248 shape). Grants of active groups join only while the switch (read in the same
-- statement as the version) is on. The snapshot does not filter on u.is_active (as 248): loaders decide on isActive.
CREATE OR REPLACE FUNCTION public.user_authorization_snapshot(p_user_id bigint)
RETURNS jsonb
LANGUAGE sql
STABLE
AS $function$
  SELECT jsonb_build_object(
    'userId', u.user_id,
    'username', u.username,
    'isActive', u.is_active,
    'isServiceAccount', u.is_service_account,
    'roleId', u.role_id,
    'roleCode', r.role_code,
    'roleIsActive', r.is_active,
    'rowVersion', u.row_version,
    'accessGroupsEnabled', ps.access_groups_enabled,
    'version', ps.version,
    'permissions', COALESCE((
      SELECT jsonb_agg(granted.permission_name ORDER BY pc.sort_order, granted.permission_name)
      FROM (
        SELECT rp.permission_name
        FROM public.role_permissions rp
        WHERE rp.role_id = u.role_id AND rp.is_enabled
        UNION
        SELECT agp.permission_name
        FROM public.user_access_groups uag
        JOIN public.access_groups ag ON ag.group_id = uag.group_id AND ag.is_active
        JOIN public.access_group_permissions agp ON agp.group_id = ag.group_id
        WHERE uag.user_id = u.user_id AND ps.access_groups_enabled
      ) granted
      JOIN public.permissions_catalog pc ON pc.permission_name = granted.permission_name AND pc.is_active
    ), '[]'::jsonb),
    'scopes', COALESCE((
      SELECT jsonb_object_agg(keys.scope_key, COALESCE((
        SELECT jsonb_agg(granted.scope_value ORDER BY granted.scope_value)
        FROM (
          SELECT rps.scope_value
          FROM public.role_policy_scopes rps
          WHERE rps.role_id = u.role_id AND rps.scope_key = keys.scope_key AND rps.scope_value <> 'none'
          UNION
          SELECT ags.scope_value
          FROM public.user_access_groups uag
          JOIN public.access_groups ag ON ag.group_id = uag.group_id AND ag.is_active
          JOIN public.access_group_scopes ags ON ags.group_id = ag.group_id AND ags.scope_key = keys.scope_key
          WHERE uag.user_id = u.user_id AND ps.access_groups_enabled
        ) granted
      ), '[]'::jsonb))
      FROM (SELECT DISTINCT scope_key FROM public.policy_scope_allowed_values) keys
    ), '{}'::jsonb)
  )
  FROM public.users u
  JOIN public.roles r ON r.role_id = u.role_id
  CROSS JOIN public.permissions_state ps
  WHERE u.user_id = p_user_id
    AND ps.id;
$function$;

COMMENT ON FUNCTION public.user_authorization_snapshot(bigint) IS
  'Access groups M2: effective authorization of one user in one statement (base role ∪ active groups while access_groups_enabled).';

COMMIT;
