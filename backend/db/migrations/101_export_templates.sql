-- Flexible, backend-evaluated export templates. Initial format: BIFF8 XLS.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS export_templates (
  export_template_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT,
  name TEXT NOT NULL,
  description TEXT,
  target_screen TEXT NOT NULL,
  source_type TEXT NOT NULL,
  format TEXT NOT NULL,
  sheet_name TEXT NOT NULL,
  schema_version SMALLINT NOT NULL DEFAULT 1,
  template_hash TEXT NOT NULL,
  columns_json JSONB NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,
  is_default BOOLEAN NOT NULL DEFAULT false,
  version INTEGER NOT NULL DEFAULT 1,
  created_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  deleted_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ,
  CONSTRAINT chk_export_templates_target CHECK (target_screen IN ('bazis_cut_set', 'bazis_project_card')),
  CONSTRAINT chk_export_templates_source CHECK (source_type IN ('bazis_cut_set_detail', 'bazis_project_panel')),
  CONSTRAINT chk_export_templates_target_source CHECK (
    (target_screen='bazis_cut_set' AND source_type='bazis_cut_set_detail') OR
    (target_screen='bazis_project_card' AND source_type='bazis_project_panel')
  ),
  CONSTRAINT chk_export_templates_format CHECK (format='xls_biff8'),
  CONSTRAINT chk_export_templates_name CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  CONSTRAINT chk_export_templates_sheet_name CHECK (
    length(btrim(sheet_name)) BETWEEN 1 AND 31 AND sheet_name !~ '[\[\]:*?/\\]'
  ),
  CONSTRAINT chk_export_templates_schema_version CHECK (schema_version=1),
  CONSTRAINT chk_export_templates_hash CHECK (template_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT chk_export_templates_columns_array CHECK (jsonb_typeof(columns_json)='array'),
  CONSTRAINT chk_export_templates_version CHECK (version > 0),
  CONSTRAINT chk_export_templates_default_active CHECK (NOT is_default OR (is_active AND deleted_at IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_export_templates_code
  ON export_templates (code) WHERE code IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_export_templates_live_name
  ON export_templates (target_screen, source_type, format, lower(name))
  WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_export_templates_active_default
  ON export_templates (target_screen, source_type, format)
  WHERE deleted_at IS NULL AND is_active=true AND is_default=true;

CREATE INDEX IF NOT EXISTS idx_export_templates_runtime
  ON export_templates (target_screen, source_type, format, is_default DESC, name)
  WHERE deleted_at IS NULL AND is_active=true;

