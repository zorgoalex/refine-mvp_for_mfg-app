       template_seed.target_screen, template_seed.source_type, 'xls_biff8', 'Детали для раскроя',
       1, encode(digest(jsonb_build_object('schemaVersion', 1, 'columns', seed.columns_json)::text, 'sha256'), 'hex'),
       seed.columns_json, true, true, 1
FROM template_seed CROSS JOIN seed
ON CONFLICT (code) WHERE code IS NOT NULL DO NOTHING;

