-- 056_projects.sql
-- Родительская сущность всех заказов (UI «Проект»).

BEGIN;

CREATE TABLE IF NOT EXISTS projects (
  project_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  code CITEXT NOT NULL,
  name VARCHAR(300) NOT NULL,
  client_id BIGINT NOT NULL,
  notes TEXT,
  delete_flag BOOLEAN NOT NULL DEFAULT false,
  version INTEGER NOT NULL DEFAULT 0,
  created_by BIGINT NOT NULL,
  edited_by BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT now(),
  updated_at TIMESTAMP NOT NULL DEFAULT now(),
  CONSTRAINT pk_projects PRIMARY KEY (project_id),
  CONSTRAINT uq_projects_code UNIQUE (code),
  CONSTRAINT chk_projects_code CHECK (code ~ '^[0-9A-Za-zА-Яа-яЁё-]{1,20}$'),
  CONSTRAINT uq_projects_id_client UNIQUE (project_id, client_id),
  CONSTRAINT fk_projects_client FOREIGN KEY (client_id)
    REFERENCES clients(client_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_projects_created_by FOREIGN KEY (created_by)
    REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_projects_edited_by FOREIGN KEY (edited_by)
    REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS ix_projects_client ON projects(client_id);

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS project_id BIGINT;

-- Backfill: один проект на каждый существующий заказ, включая soft-deleted.
WITH numbered AS (
  SELECT
    o.order_id,
    o.order_name,
    o.client_id,
    o.created_by,
    nextval(pg_get_serial_sequence('public.projects', 'project_id')) AS nid
  FROM orders o
  WHERE o.project_id IS NULL
),
ins AS (
  INSERT INTO projects (project_id, code, name, client_id, created_by)
  SELECT
    n.nid,
    'МП-' || n.nid,
    LEFT(COALESCE(n.order_name, ''), 300),
    n.client_id,
    n.created_by
  FROM numbered n
)
UPDATE orders o
SET project_id = n.nid
FROM numbered n
WHERE o.order_id = n.order_id;

SELECT setval(pg_get_serial_sequence('public.projects', 'project_id'),
              GREATEST((SELECT COALESCE(MAX(project_id), 1) FROM projects), 1));

ALTER TABLE orders
  ALTER COLUMN project_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'fk_orders_project_client'
  ) THEN
    ALTER TABLE orders
      ADD CONSTRAINT fk_orders_project_client
      FOREIGN KEY (project_id, client_id)
      REFERENCES projects (project_id, client_id)
      ON UPDATE CASCADE
      ON DELETE RESTRICT;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_orders_project ON orders(project_id);

CREATE OR REPLACE VIEW projects_view AS
SELECT
  p.project_id,
  p.code,
  p.name,
  p.client_id,
  c.client_name,
  p.notes,
  p.delete_flag,
  p.version,
  p.created_by,
  p.edited_by,
  p.created_at,
  p.updated_at,
  COUNT(o.order_id) FILTER (WHERE o.delete_flag = false) AS orders_count,
  COALESCE(SUM(o.final_amount) FILTER (WHERE o.delete_flag = false), 0) AS total_final_amount,
  COALESCE(SUM(o.paid_amount) FILTER (WHERE o.delete_flag = false), 0) AS total_paid_amount,
  MIN(o.order_date) FILTER (WHERE o.delete_flag = false) AS first_order_date,
  MAX(o.planned_completion_date) FILTER (WHERE o.delete_flag = false) AS last_planned_completion_date
FROM projects p
JOIN clients c ON c.client_id = p.client_id
LEFT JOIN orders o ON o.project_id = p.project_id
GROUP BY
  p.project_id,
  p.code,
  p.name,
  p.client_id,
  c.client_name,
  p.notes,
  p.delete_flag,
  p.version,
  p.created_by,
  p.edited_by,
  p.created_at,
  p.updated_at;

CREATE OR REPLACE VIEW orders_view AS
SELECT
    ord.order_id, ord.order_name,
    CASE
        WHEN order_name_digits.value = '' THEN NULL
        WHEN length(order_name_digits.value) > 10 THEN NULL
        WHEN order_name_digits.value::BIGINT > 2147483647 THEN NULL
        ELSE order_name_digits.value::INTEGER
    END AS order_name_numeric,
    ord.client_id, c.client_name, ord.order_date, ord.priority,
    d.doweling_order_id, d.doweling_order_name, emd.full_name AS design_engineer,
    ord.completion_date, ord.planned_completion_date,
    os.order_status_name, ps.payment_status_name, pr.production_status_name,
    ord.issue_date, ord.total_amount, ord.final_amount, ord.discount, ord.surcharge,
    ord.paid_amount, ord.payment_date, ord.parts_count, ord.total_area,
    mt.milling_type_name, et.edge_type_name, f.film_name,
    smt.name AS material_name,
    ord.notes, ord.link_cutting_file, ord.link_cutting_image_file,
    ord.ref_key_1c AS order_ref_key_1c, c.ref_key_1c AS client_ref_key_1c,
    ord.manager_id, ord.created_by, ord.edited_by, ord.created_at, ord.updated_at,
    ord.version, ord.sheet_material_type_id,
    ord.project_id,
    mp.code AS project_code,
    (mp.code || '-' || ord.order_name) AS order_full_number
FROM orders ord
CROSS JOIN LATERAL (
    VALUES (regexp_replace(COALESCE(ord.order_name, ''), '\D', '', 'g'))
) AS order_name_digits(value)
LEFT JOIN clients c ON ord.client_id = c.client_id
LEFT JOIN doweling_orders d ON ord.order_id = d.order_id
LEFT JOIN employees emd ON d.design_engineer_id = emd.employee_id
LEFT JOIN order_statuses os ON ord.order_status_id = os.order_status_id
LEFT JOIN payment_statuses ps ON ord.payment_status_id = ps.payment_status_id
LEFT JOIN production_statuses pr ON ord.production_status_id = pr.production_status_id
LEFT JOIN milling_types mt ON ord.milling_type_id = mt.milling_type_id
LEFT JOIN edge_types et ON ord.edge_type_id = et.edge_type_id
LEFT JOIN films f ON ord.film_id = f.film_id
LEFT JOIN sheet_material_types smt ON ord.sheet_material_type_id = smt.sheet_material_type_id
JOIN projects mp ON ord.project_id = mp.project_id
WHERE ord.delete_flag = false
ORDER BY ord.order_id DESC;

COMMIT;
