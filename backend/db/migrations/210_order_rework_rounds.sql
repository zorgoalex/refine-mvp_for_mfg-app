  PRIMARY KEY (order_production_round_id, detail_id),
  CONSTRAINT chk_order_production_round_details_from_round CHECK (from_production_round >= 1),
  CONSTRAINT chk_order_production_round_details_source CHECK (added_by_source IN ('start', 'extend'))
