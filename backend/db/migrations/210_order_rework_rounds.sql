-- 6c. emit_one: при erp.realtime_defer='on' — запись в очередь вместо лока
-- stream. Без переменной тело идентично 098 (проверяется тестом миграции).
CREATE OR REPLACE FUNCTION order_realtime_emit_one(
  p_order_id BIGINT,
  p_domains TEXT[],
  p_detail_ids BIGINT[],
  p_source_type TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
  v_enabled BOOLEAN;
  v_max_detail_ids INTEGER;
  v_domains TEXT[];
  v_detail_ids BIGINT[];
  v_stream order_realtime_stream%ROWTYPE;
BEGIN
  SELECT enabled INTO v_enabled FROM order_realtime_bridge_config();
  SELECT order_realtime_bridge_max_detail_ids() INTO v_max_detail_ids;
  IF NOT COALESCE(v_enabled, false) THEN
    RETURN false;
  END IF;

  SELECT array_agg(domain_name ORDER BY domain_name)
  INTO v_domains
  FROM (
    SELECT DISTINCT domain_name
    FROM unnest(p_domains) AS domain_name
    WHERE domain_name IN ('detail_status', 'cut_refs')
  ) normalized;
  IF COALESCE(cardinality(v_domains), 0) = 0 THEN
    RAISE EXCEPTION 'ORDER_REALTIME_INVALID_DOMAIN' USING ERRCODE = 'P0001';
  END IF;

  SELECT array_agg(detail_id ORDER BY detail_id)
  INTO v_detail_ids
  FROM (
    SELECT DISTINCT detail_id
    FROM unnest(COALESCE(p_detail_ids, ARRAY[]::BIGINT[])) AS detail_id
    WHERE detail_id > 0
  ) normalized;
  IF COALESCE(cardinality(v_detail_ids), 0) > v_max_detail_ids THEN
    v_detail_ids := NULL;
  END IF;

  -- Операции кругов «Переделки» не берут stream в своей транзакции (план §5.7
  -- п.5): эмиссия откладывается и доставляется дренажом после коммита.
  IF COALESCE(current_setting('erp.realtime_defer', true), '') = 'on' THEN
    INSERT INTO order_realtime_deferred (order_id, domains, detail_ids, source_type)
    VALUES (
      p_order_id,
      v_domains,
      CASE WHEN cardinality(v_detail_ids) = 0 THEN NULL ELSE v_detail_ids END,
      left(p_source_type, 200)
    );
    RETURN false;
  END IF;

  INSERT INTO order_realtime_stream (order_id)
  SELECT p_order_id
  WHERE EXISTS (SELECT 1 FROM orders WHERE order_id = p_order_id)
  ON CONFLICT (order_id) DO NOTHING;

  PERFORM 1
  FROM order_realtime_stream
  WHERE order_id = p_order_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE order_realtime_stream
  SET commit_sequence = commit_sequence + 1,
      detail_status_revision = detail_status_revision
        + CASE WHEN 'detail_status' = ANY(v_domains) THEN 1 ELSE 0 END,
      cut_refs_revision = cut_refs_revision
        + CASE WHEN 'cut_refs' = ANY(v_domains) THEN 1 ELSE 0 END,
      updated_at = now()
  WHERE order_id = p_order_id
  RETURNING * INTO v_stream;

  INSERT INTO realtime_event_log (
    order_id, commit_sequence, detail_status_revision, cut_refs_revision,
    domains, detail_ids, schema_version, source_type, source_key, occurred_at
  )
  VALUES (
    p_order_id,
    v_stream.commit_sequence,
    CASE WHEN 'detail_status' = ANY(v_domains) THEN v_stream.detail_status_revision ELSE NULL END,
    CASE WHEN 'cut_refs' = ANY(v_domains) THEN v_stream.cut_refs_revision ELSE NULL END,
    v_domains,
    CASE WHEN cardinality(v_detail_ids) = 0 THEN NULL ELSE v_detail_ids END,
    1,
    left(p_source_type, 200),
    -- Technical transport identity only. Business audit/idempotency remains
    -- owned by the command or legacy writer that performed the mutation.
    left('db-bridge:' || p_source_type || ':' || txid_current()::text || ':' || v_stream.commit_sequence::text, 200),
    statement_timestamp()
  );
  RETURN true;
END
$$;

COMMENT ON FUNCTION order_realtime_emit_one(BIGINT, TEXT[], BIGINT[], TEXT)
  IS 'order-realtime-producer-bridge-v1';

-- 7. Guard статуса «Переделка» -------------------------------------------------

-- Вход в «Переделку» — только командой переделки (erp.rework_command='on') или
-- backend-импортом snapshot после валидации ('import'); Hasura/SQL/прочие
-- писатели получают отказ (§5.2).
CREATE OR REPLACE FUNCTION public.trg_orders_rework_status_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_rework_id SMALLINT;
BEGIN
  SELECT order_status_id INTO v_rework_id
  FROM public.order_statuses
  WHERE order_status_code = 'rework';
  IF v_rework_id IS NULL OR NEW.order_status_id IS DISTINCT FROM v_rework_id THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.order_status_id IS NOT DISTINCT FROM NEW.order_status_id THEN
    RETURN NEW;
  END IF;
  IF COALESCE(current_setting('erp.rework_command', true), '') NOT IN ('on', 'import') THEN
    RAISE EXCEPTION 'ORDER_REWORK_REQUIRES_COMMAND' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS trg_orders_rework_status_guard ON public.orders;
CREATE TRIGGER trg_orders_rework_status_guard
BEFORE INSERT OR UPDATE OF order_status_id ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.trg_orders_rework_status_guard();

-- Согласованность на коммите (§5.4): при «Готов к выдаче»/«Выдан»/«Завершен»
-- открытого круга нет; статус «Переделка» — только при открытом круге.
CREATE OR REPLACE FUNCTION public.assert_order_rework_round_consistency(p_order_id BIGINT)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  v_code TEXT;
  v_open BOOLEAN;
BEGIN
  SELECT s.order_status_code INTO v_code
  FROM public.orders o
  JOIN public.order_statuses s ON s.order_status_id = o.order_status_id
  WHERE o.order_id = p_order_id;
  IF NOT FOUND THEN
    RETURN;
  END IF;
  SELECT EXISTS (
    SELECT 1 FROM public.order_production_rounds
    WHERE order_id = p_order_id AND closed_at IS NULL
  ) INTO v_open;
  IF v_open AND v_code IN ('legacy_6', 'legacy_7', 'legacy_8') THEN
    RAISE EXCEPTION 'ORDER_REWORK_ROUND_OPEN_AT_TERMINAL' USING ERRCODE = 'P0001';
  END IF;
  IF NOT v_open AND v_code = 'rework' THEN
    RAISE EXCEPTION 'ORDER_REWORK_STATUS_WITHOUT_ROUND' USING ERRCODE = 'P0001';
  END IF;
END
$$;

CREATE OR REPLACE FUNCTION public.ctrg_orders_rework_round_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  PERFORM public.assert_order_rework_round_consistency(NEW.order_id);
  RETURN NULL;
END
$$;

DROP TRIGGER IF EXISTS ctrg_orders_rework_round_consistency ON public.orders;
CREATE CONSTRAINT TRIGGER ctrg_orders_rework_round_consistency
AFTER INSERT OR UPDATE OF order_status_id ON public.orders
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.ctrg_orders_rework_round_consistency();

-- Круги: вставка, закрытие, удаление и перенос между заказами проверяют и
-- прежний, и новый заказ (удаление заказа каскадом — заказа уже нет, выход).
CREATE OR REPLACE FUNCTION public.ctrg_order_production_rounds_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM public.assert_order_rework_round_consistency(OLD.order_id);
  END IF;
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    PERFORM public.assert_order_rework_round_consistency(NEW.order_id);
  END IF;
  RETURN NULL;
END
$$;

DROP TRIGGER IF EXISTS ctrg_order_production_rounds_consistency ON public.order_production_rounds;
CREATE CONSTRAINT TRIGGER ctrg_order_production_rounds_consistency
AFTER INSERT OR UPDATE OR DELETE ON public.order_production_rounds
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.ctrg_order_production_rounds_consistency();
