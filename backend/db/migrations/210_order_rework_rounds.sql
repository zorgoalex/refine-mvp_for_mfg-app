-- 6. Realtime ------------------------------------------------------------------

-- 6a. Строка stream существует для каждого заказа заранее: дренаж отложенной
-- эмиссии никогда не вставляет stream (нет спекулятивного ожидания). Нулевая
-- строка эквивалентна отсутствию (читатели LEFT JOIN + COALESCE).
INSERT INTO public.order_realtime_stream (order_id)
SELECT order_id FROM public.orders
ON CONFLICT (order_id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.trg_order_realtime_stream_on_order_insert()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  INSERT INTO public.order_realtime_stream (order_id)
  SELECT order_id FROM new_rows
  ON CONFLICT (order_id) DO NOTHING;
  RETURN NULL;
END
$$;

DROP TRIGGER IF EXISTS trg_order_realtime_stream_on_order_insert ON public.orders;
CREATE TRIGGER trg_order_realtime_stream_on_order_insert
AFTER INSERT ON public.orders
REFERENCING NEW TABLE AS new_rows
FOR EACH STATEMENT EXECUTE FUNCTION public.trg_order_realtime_stream_on_order_insert();

