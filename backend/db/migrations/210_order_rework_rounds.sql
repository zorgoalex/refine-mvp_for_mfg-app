-- 3. Круги производства -------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.order_production_rounds (
  order_production_round_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  round_no SMALLINT NOT NULL,
  mode TEXT NOT NULL,
  reason_id SMALLINT NOT NULL REFERENCES public.order_rework_reasons(order_rework_reason_id),
  reason_comment TEXT NULL,
  from_order_status_id SMALLINT NOT NULL REFERENCES public.order_statuses(order_status_id),
  from_order_production_round SMALLINT NOT NULL,
  source TEXT NOT NULL DEFAULT 'manual',
  -- Этап 2 (автозапуск): ссылки без FK, источник может быть заархивирован.
  source_cut_job_id BIGINT NULL,
  source_packet_id BIGINT NULL,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  started_by BIGINT NULL REFERENCES public.users(user_id) ON DELETE SET NULL,
  reason_clarified_at TIMESTAMPTZ NULL,
  reason_clarified_by BIGINT NULL REFERENCES public.users(user_id) ON DELETE SET NULL,
  closed_at TIMESTAMPTZ NULL,
  closed_by BIGINT NULL REFERENCES public.users(user_id) ON DELETE SET NULL,
  close_reason TEXT NULL,
  event_seq SMALLINT NOT NULL DEFAULT 0,
  request_id TEXT NULL,
  idempotency_key TEXT NULL,
  CONSTRAINT uq_order_production_rounds_order_round UNIQUE (order_id, round_no),
  CONSTRAINT uq_order_production_rounds_idempotency UNIQUE (idempotency_key),
  CONSTRAINT chk_order_production_rounds_round_no CHECK (round_no >= 2),
  CONSTRAINT chk_order_production_rounds_mode CHECK (mode IN ('after_ready', 'in_production')),
  CONSTRAINT chk_order_production_rounds_source CHECK (source IN ('manual', 'auto_cut_repeat', 'import')),
  CONSTRAINT chk_order_production_rounds_from_round CHECK (from_order_production_round >= 1 AND from_order_production_round < round_no),
  CONSTRAINT chk_order_production_rounds_comment CHECK (reason_comment IS NULL OR char_length(reason_comment) <= 2000),
  CONSTRAINT chk_order_production_rounds_close_reason CHECK (
    close_reason IS NULL OR close_reason IN ('ready', 'issued', 'completed', 'false_positive')
  ),
  CONSTRAINT chk_order_production_rounds_closed CHECK ((closed_at IS NULL) = (close_reason IS NULL)),
  CONSTRAINT chk_order_production_rounds_event_seq CHECK (event_seq >= 0)
);

-- Не больше одного открытого круга на заказ.
