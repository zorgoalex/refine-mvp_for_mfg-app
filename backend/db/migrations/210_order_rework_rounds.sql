-- «Переделка» и круги производства — миграция A (аддитивная).
-- План: spec_erp/plans/2026-09-27-order-rework-status-plan.md v18 (§4.1, §5.2,
-- §5.4, §5.7 п.5, §7.2).
--
-- Совместима со старым backend: всё новое имеет DEFAULT, старые unique-индексы
-- production_status_events остаются (их удаляет миграция B после backend A),
-- статус «Переделка» ставит только команда (guard ниже), без переменной
-- erp.realtime_defer order_realtime_emit_one ведёт себя как раньше.
--
-- 1. Статус заказа «Переделка» (code rework, sort 45).
-- 2. Справочник причин переделки (+ системная «Уточнить»).
-- 3. Круги производства: rounds, round_details (before-state), round_sources.
-- 4. Текущий/последний круг заказа и детали; round_no у событий этапов и
--    дополнительные unique-индексы (detail|order, status, round).
-- 5. Круг у строк раскроя (учёт перерасхода).
-- 6. Realtime: строка stream создаётся заранее (backfill + триггер на orders),
--    очередь отложенной эмиссии, ветка erp.realtime_defer в emit_one.
-- 7. Guard входа в «Переделку» и deferred-согласованность статус ↔ открытый круг.

-- 1. Статус «Переделка» -------------------------------------------------------

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.order_statuses WHERE order_status_code = 'rework') THEN
    IF EXISTS (SELECT 1 FROM public.order_statuses WHERE order_status_name = 'Переделка') THEN
      RAISE EXCEPTION 'ORDER_REWORK_STATUS_NAME_TAKEN: status «Переделка» exists with another code';
    END IF;
    -- identity может отставать от max после restore (erp_test reload drift).
    PERFORM setval(
      pg_get_serial_sequence('public.order_statuses', 'order_status_id'),
      GREATEST((SELECT max(order_status_id) FROM public.order_statuses), 1)
    );
    INSERT INTO public.order_statuses (
      order_status_code, order_status_name, sort_order, color, description, is_active
    ) VALUES (
      'rework',
      'Переделка',
      45,
      '#D97706',
      'Повторное производство выбранных деталей после готовности заказа (круг производства ≥ 2). Ставится только командой переделки.',
      true
    );
  END IF;
END $$;

