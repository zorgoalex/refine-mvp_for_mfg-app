-- Backfill: marks for the stages the live details are in now. Nothing is
-- removed. One summary audit row; no outbox (history, not a new transition).
WITH live AS (
  SELECT od.order_id, od.production_status_id
    FROM order_details od
   WHERE COALESCE(od.delete_flag, false) = false AND od.production_status_id IS NOT NULL
  UNION
  SELECT h.order_id, h.production_status_id
    FROM order_hdf_details h
    JOIN production_statuses hs ON hs.production_status_id = h.production_status_id AND hs.production_status_code = 'hdf'
   WHERE COALESCE(h.delete_flag, false) = false
), inserted AS (
  INSERT INTO production_status_events (order_id, production_status_id, event_by, note, payload)
  SELECT l.order_id, l.production_status_id, NULL, 'По статусу деталей',
         jsonb_build_object('origin', 'detail_status_backfill', 'migration', '266')
    FROM live l
    JOIN orders o ON o.order_id = l.order_id AND o.order_kind = 'production_order'
    JOIN production_statuses ps ON ps.production_status_id = l.production_status_id
     AND ps.is_active AND ps.production_status_code <> 'new'
  ON CONFLICT DO NOTHING
  RETURNING order_id, production_status_id
)
INSERT INTO audit_log (event, entity_type, entity_id, user_id, username, request_id, metadata_json, source)
SELECT 'production_stage_mark.auto_backfill', 'migration', '266', NULL, 'system', 'migration-266',
       jsonb_build_object('origin', 'detail_status_backfill', 'inserted', count(*),
         'byStatus', COALESCE((SELECT jsonb_object_agg(production_status_id::text, cnt)
                                 FROM (SELECT production_status_id, count(*) AS cnt FROM inserted GROUP BY 1) s), '{}'::jsonb)),
       'migration'
  FROM inserted;

COMMIT;
