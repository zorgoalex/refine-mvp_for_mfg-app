BEGIN;
SET LOCAL lock_timeout = '5s';

-- Order stage marks (production_status_events with order_id) follow detail stages.
-- Manual marks from the stage menu and marks written here share one level:
-- the last action wins. A detail entering stage S sets the mark S; the last
-- detail leaving stage S clears it. Only stages touched by a transition change.
-- «Новый» and inactive stages are never marked. HDF details count only for the
-- «ХДФ» stage. The order version is not bumped: an open editor keeps saving.

-- History of every order-level mark change, manual and automatic, for
-- recovery. history_id is taken at the change, under the order row lock that
-- both the menu command (FOR UPDATE) and the automation (FOR NO KEY UPDATE)
-- hold, so per order it is the real order of changes. Free text (note,
-- payload) lives here, not in the audit. Same sensitivity as
-- production_status_events; not exposed to Hasura.
CREATE TABLE IF NOT EXISTS production_stage_mark_history (
  history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action text NOT NULL CHECK (action IN ('insert', 'delete')),
  automatic boolean NOT NULL,
  event_id bigint NOT NULL,
  order_id bigint NOT NULL,
  production_status_id smallint NOT NULL,
  event_by bigint,
  event_at timestamp NOT NULL,
  note text,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  changed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  request_id text
);
CREATE INDEX IF NOT EXISTS idx_psmh_order_status
  ON production_stage_mark_history (order_id, production_status_id, history_id);
CREATE INDEX IF NOT EXISTS idx_psmh_changed_at ON production_stage_mark_history (changed_at);

CREATE OR REPLACE FUNCTION trg_record_stage_mark_history()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
  v_row production_status_events%ROWTYPE;
BEGIN
  IF TG_OP = 'INSERT' THEN v_row := NEW; ELSE v_row := OLD; END IF;
  IF v_row.order_id IS NULL THEN
    RETURN NULL;
  END IF;
  INSERT INTO production_stage_mark_history (
    action, automatic, event_id, order_id, production_status_id, event_by, event_at, note, payload, request_id
  ) VALUES (
    lower(TG_OP),
    CASE WHEN TG_OP = 'INSERT'
      THEN COALESCE(v_row.payload->>'origin', '') IN ('detail_status', 'detail_status_backfill')
      -- unset in a session reads as NULL: a manual delete must still be false
      ELSE COALESCE(current_setting('erp.stage_mark_automation', true), '') = 'on' END,
    v_row.event_id, v_row.order_id, v_row.production_status_id, v_row.event_by, v_row.event_at,
    v_row.note, COALESCE(v_row.payload, '{}'::jsonb), NULLIF(current_setting('erp.request_id', true), '')
  );
  RETURN NULL;
END
$function$;

DROP TRIGGER IF EXISTS trg_pse_stage_mark_history ON production_status_events;
CREATE TRIGGER trg_pse_stage_mark_history AFTER INSERT OR DELETE ON production_status_events
  FOR EACH ROW EXECUTE FUNCTION trg_record_stage_mark_history();

CREATE OR REPLACE FUNCTION apply_detail_stage_mark(
  p_order_id bigint,
  p_status_id smallint,
  p_detail_ids bigint[],
  p_entered boolean,
  p_left boolean
) RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
  v_status_code text;
  v_status_name text;
  v_status_active boolean;
  v_order_kind text;
  v_client_id bigint;
  v_present boolean;
  v_event_id bigint;
  v_active boolean;
  v_audit_id uuid;
  v_removed record;
  v_before jsonb;
  -- The HTTP request id is transaction-local (DatabaseService.transaction);
  -- standalone SQL and background jobs fall back to the transaction id.
  v_http_request_id text := NULLIF(current_setting('erp.request_id', true), '');
  v_request_id text := COALESCE(v_http_request_id, 'detail-stage-mark:' || txid_current()::text);
BEGIN
  SELECT production_status_code, production_status_name, is_active
    INTO v_status_code, v_status_name, v_status_active
    FROM production_statuses
   WHERE production_status_id = p_status_id;
  IF NOT FOUND OR NOT v_status_active OR v_status_code = 'new' THEN
    RETURN;
  END IF;

  -- Serializes concurrent transitions of one order: the presence check below
  -- runs after the lock with a fresh snapshot. NO KEY UPDATE is what the
  -- detail-summary recalculation already takes on the order row and does not
  -- conflict with the KEY SHARE locks of concurrent detail inserts (FOR UPDATE
  -- would, and could deadlock with them).
  SELECT order_kind, client_id INTO v_order_kind, v_client_id
    FROM orders
   WHERE order_id = p_order_id
   FOR NO KEY UPDATE;
  IF v_order_kind IS DISTINCT FROM 'production_order' THEN
    RETURN;
  END IF;

  v_present := EXISTS (
      SELECT 1 FROM order_details
       WHERE order_id = p_order_id
         AND COALESCE(delete_flag, false) = false
         AND production_status_id = p_status_id
    ) OR (
      v_status_code = 'hdf' AND EXISTS (
        SELECT 1 FROM order_hdf_details
         WHERE order_id = p_order_id
           AND COALESCE(delete_flag, false) = false
           AND production_status_id = p_status_id
      )
    );

  IF v_present AND p_entered THEN
    INSERT INTO production_status_events (order_id, production_status_id, event_by, note, payload)
    VALUES (
      p_order_id, p_status_id, NULL, 'По статусу деталей',
      jsonb_build_object('origin', 'detail_status', 'detailIds', to_jsonb(p_detail_ids))
    )
    ON CONFLICT DO NOTHING
    RETURNING event_id INTO v_event_id;
    v_active := true;
    v_before := jsonb_build_object('active', false);
  ELSIF NOT v_present AND p_left THEN
    -- Marks the history row of this delete as automatic.
    PERFORM set_config('erp.stage_mark_automation', 'on', true);
    DELETE FROM production_status_events
     WHERE order_id = p_order_id AND production_status_id = p_status_id
    RETURNING event_id, event_by, event_at, note, payload INTO v_removed;
    PERFORM set_config('erp.stage_mark_automation', '', true);
    v_event_id := v_removed.event_id;
    v_active := false;
    -- Free text (note, payload) goes only to production_stage_mark_history.
    v_before := jsonb_build_object('active', true, 'eventBy', v_removed.event_by,
      'eventAt', v_removed.event_at, 'removedEventId', v_removed.event_id);
  END IF;

  IF v_event_id IS NULL THEN
    RETURN;
  END IF;

  -- The actor is the system: the detail change that caused this has its own
  -- audit with the user. app.user_id is session-wide on pooled connections and
  -- is not trusted here.
  -- clock_timestamp keeps the order of several changes inside one transaction.
  INSERT INTO audit_log (
    created_at, event, entity_type, entity_id, user_id, username, request_id,
    before_json, after_json, diff_json, metadata_json, source,
    related_order_id, related_client_id, related_production_event_id,
    status_field, status_id, status_name, status_code, stage_code
  ) VALUES (
    clock_timestamp(),
    CASE WHEN v_active THEN 'production_stage_mark.auto_activate' ELSE 'production_stage_mark.auto_deactivate' END,
    'order', p_order_id::text, NULL, 'system', v_request_id,
    v_before,
    jsonb_build_object('active', v_active, 'productionEventId', v_event_id,
      'productionStatusId', p_status_id, 'productionStatusCode', v_status_code),
    jsonb_build_object('active', jsonb_build_object('before', NOT v_active, 'after', v_active)),
    jsonb_build_object('origin', 'detail_status', 'orderId', p_order_id, 'clientId', v_client_id,
      'productionEventId', v_event_id, 'productionStatusId', p_status_id,
      'productionStatusCode', v_status_code, 'detailIds', to_jsonb(p_detail_ids),
      'action', CASE WHEN v_active THEN 'activate' ELSE 'deactivate' END,
      'statusField', 'productionStage', 'transactionId', txid_current(),
      'causationRequestId', v_http_request_id),
    'detail_status_trigger',
    p_order_id, v_client_id, v_event_id,
    'productionStage', p_status_id, v_status_name, v_status_code, v_status_code
  )
  RETURNING audit_id INTO v_audit_id;

  -- Same domain event as a manual menu toggle (production-actions), told apart
  -- by origin/scope. No relay consumer handles stage events yet; a relay run
  -- marks them processed. A future consumer replays them by re-queuing
  -- (status='pending') rows of these event types from its start date.
  INSERT INTO outbox_events (event_type, aggregate_type, aggregate_id, payload_json, idempotency_key)
  VALUES (
    CASE WHEN v_active THEN 'production.stage_activated' ELSE 'production.stage_deactivated' END,
    'order', p_order_id::text,
    jsonb_build_object(
      'eventType', CASE WHEN v_active THEN 'production.stage_activated' ELSE 'production.stage_deactivated' END,
      'origin', 'detail_status',
      'actorUserId', NULL, 'requestId', v_request_id, 'auditId', v_audit_id,
      'entityType', 'order', 'entityId', p_order_id::text, 'orderId', p_order_id, 'clientId', v_client_id,
      'productionEventId', v_event_id, 'productionStatusId', p_status_id,
      'productionStatusCode', v_status_code, 'detailIds', to_jsonb(p_detail_ids),
      'action', CASE WHEN v_active THEN 'activate' ELSE 'deactivate' END,
      'scope', jsonb_build_object('source', 'detail_status')
    ),
    'detail-stage-mark:' || v_audit_id::text
  );
END
$function$;

-- One call per touched (order, stage), in order_id order (lock order).
CREATE OR REPLACE FUNCTION apply_detail_stage_mark_changes(p_changes jsonb)
RETURNS void
LANGUAGE plpgsql
AS $function$
DECLARE
  v_row record;
BEGIN
  FOR v_row IN
    SELECT (c->>'order_id')::bigint AS order_id,
           (c->>'status_id')::smallint AS status_id,
           array_agg(DISTINCT (c->>'detail_id')::bigint ORDER BY (c->>'detail_id')::bigint) AS detail_ids,
           bool_or((c->>'entered')::boolean) AS entered,
           bool_or(NOT (c->>'entered')::boolean) AS left_stage
      FROM jsonb_array_elements(p_changes) c
     GROUP BY 1, 2
     ORDER BY 1, 2
  LOOP
    PERFORM apply_detail_stage_mark(v_row.order_id, v_row.status_id, v_row.detail_ids, v_row.entered, v_row.left_stage);
  END LOOP;
END
$function$;

-- Generic statement trigger for order_details and order_hdf_details.
-- TG_ARGV[0] = 'hdf' limits HDF details to the «ХДФ» stage.
CREATE OR REPLACE FUNCTION trg_detail_stage_marks()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
  v_changes jsonb;
  v_hdf_only boolean := TG_ARGV[0] = 'hdf';
  v_hdf_status_id smallint;
BEGIN
  IF v_hdf_only THEN
    SELECT production_status_id INTO v_hdf_status_id FROM production_statuses WHERE production_status_code = 'hdf';
  END IF;

  IF TG_OP = 'INSERT' THEN
    SELECT jsonb_agg(jsonb_build_object('order_id', n.order_id, 'status_id', n.production_status_id,
             'detail_id', n.detail_key, 'entered', true))
      INTO v_changes
      FROM (SELECT order_id, production_status_id, delete_flag,
                   COALESCE((to_jsonb(r)->>'detail_id'), (to_jsonb(r)->>'order_hdf_detail_id'))::bigint AS detail_key
              FROM new_rows r) n
     WHERE n.order_id IS NOT NULL AND n.production_status_id IS NOT NULL
       AND COALESCE(n.delete_flag, false) = false
       AND (NOT v_hdf_only OR n.production_status_id = v_hdf_status_id);
  ELSIF TG_OP = 'DELETE' THEN
    SELECT jsonb_agg(jsonb_build_object('order_id', o.order_id, 'status_id', o.production_status_id,
             'detail_id', o.detail_key, 'entered', false))
      INTO v_changes
      FROM (SELECT order_id, production_status_id, delete_flag,
                   COALESCE((to_jsonb(r)->>'detail_id'), (to_jsonb(r)->>'order_hdf_detail_id'))::bigint AS detail_key
              FROM old_rows r) o
     WHERE o.order_id IS NOT NULL AND o.production_status_id IS NOT NULL
       AND COALESCE(o.delete_flag, false) = false
       AND (NOT v_hdf_only OR o.production_status_id = v_hdf_status_id);
  ELSE
    WITH pairs AS (
      SELECT o.order_id AS old_order_id, o.production_status_id AS old_status_id,
             COALESCE(o.delete_flag, false) AS old_deleted,
             n.order_id AS new_order_id, n.production_status_id AS new_status_id,
             COALESCE(n.delete_flag, false) AS new_deleted, o.detail_key
        FROM (SELECT r.*, COALESCE((to_jsonb(r)->>'detail_id'), (to_jsonb(r)->>'order_hdf_detail_id'))::bigint AS detail_key FROM old_rows r) o
        JOIN (SELECT r.*, COALESCE((to_jsonb(r)->>'detail_id'), (to_jsonb(r)->>'order_hdf_detail_id'))::bigint AS detail_key FROM new_rows r) n
          USING (detail_key)
       WHERE o.production_status_id IS DISTINCT FROM n.production_status_id
          OR COALESCE(o.delete_flag, false) IS DISTINCT FROM COALESCE(n.delete_flag, false)
          OR o.order_id IS DISTINCT FROM n.order_id
    ), changes AS (
      SELECT old_order_id AS order_id, old_status_id AS status_id, detail_key, false AS entered
        FROM pairs WHERE old_order_id IS NOT NULL AND old_status_id IS NOT NULL AND NOT old_deleted
      UNION ALL
      SELECT new_order_id, new_status_id, detail_key, true
        FROM pairs WHERE new_order_id IS NOT NULL AND new_status_id IS NOT NULL AND NOT new_deleted
    )
    SELECT jsonb_agg(jsonb_build_object('order_id', order_id, 'status_id', status_id,
             'detail_id', detail_key, 'entered', entered))
      INTO v_changes
      FROM changes
     WHERE NOT v_hdf_only OR status_id = v_hdf_status_id;
  END IF;

  IF v_changes IS NOT NULL THEN
    PERFORM apply_detail_stage_mark_changes(v_changes);
  END IF;
  RETURN NULL;
END
$function$;

