// Seed: an order with milling_type_id/edge_type_id/film_id set on the header,
// and a detail with sheet_material_type_id set, material_id = NULL (post-034).
// ---------------------------------------------------------------------------
async function seedVariantBOrder(client: Client): Promise<{ orderId: number; smtId: number }> {
  // Ensure milling_type_id=1, edge_type_id=1 exist (inserted by bootstrap029).
  // Insert a film row for film_id reference.
  await client.query(`INSERT INTO films (film_id, film_name) VALUES (1, 'Плёнка тест') ON CONFLICT DO NOTHING`);

  // Insert order_statuses and payment_statuses needed by the header query joins.
  await client.query(`INSERT INTO order_statuses (order_status_id, order_status_name) VALUES (1, 'Новый') ON CONFLICT DO NOTHING`);
  await client.query(`INSERT INTO payment_statuses (payment_status_id, payment_status_name) VALUES (1, 'Не оплачен') ON CONFLICT DO NOTHING`);

  // Insert a sheet_material_type.
  const smtRes = await client.query<{ sheet_material_type_id: number }>(
    `INSERT INTO sheet_material_types (name, unit_id, material_type_id, width_mm, height_mm, is_active)
     VALUES ('МДФ VB read-repo тест', 1, 1, 2800, 2070, true)
     RETURNING sheet_material_type_id`,
  );
  const smtId = smtRes.rows[0].sheet_material_type_id;

  // Insert order with header refs set (milling_type_id=1, edge_type_id=1, film_id=1).
  // post-034: material_id=NULL on the order (sheet_material_type_id is authoritative).
  const orderRes = await client.query<{ order_id: number }>(
    `INSERT INTO orders (order_name, sheet_eligible, sheet_material_type_id, milling_type_id, edge_type_id, film_id,
       order_status_id, payment_status_id, total_amount, final_amount, paid_amount, parts_count, total_area,
       discount, surcharge)
     VALUES ('VB read-repo тест заказ', true, $1, 1, 1, 1, 1, 1, 0, 0, 0, 1, 0.24, 0, 0)
     RETURNING order_id`,
    [smtId],
  );
  const orderId = orderRes.rows[0].order_id;

  // Detail: material_id=NULL (Variant B), sheet_material_type_id=smtId.
  await client.query(
    `INSERT INTO order_details (order_id, detail_number, detail_name, height, width, quantity, area,
       material_id, sheet_material_type_id, milling_type_id, edge_type_id, priority)
     VALUES ($1, 1, 'VB read-repo деталь', 600, 400, 1, 0.24, NULL, $2, 1, 1, 100)`,
    [orderId, smtId],
  );

  return { orderId, smtId };
}

d('PgOrderReadRepository integration — both flag states (critic R3)', () => {
  const client = new Client({ connectionString: url });
  const schema = `vb_read_repo_${process.hrtime.bigint()}`;
  let orderId: number;
  let smtId: number;

  beforeAll(async () => {
    await client.connect();

    // Isolated schema — all objects land here, not in public.
    await client.query(`CREATE SCHEMA ${schema}`);
    await client.query(`SET search_path TO ${schema}, public`);

    // Apply the full Variant B forward chain.
    await bootstrapVariantBSchema(client);
    await seedVariantAMain(client);
    await client.query(mig('034_order_material_sunset_legacy.sql'));

    // Add stub tables required by the repository.
    await createStubTables(client);

    // Seed one Variant-B order (material_id=NULL on detail, header refs set).
    const seed = await seedVariantBOrder(client);
    orderId = seed.orderId;
    smtId = seed.smtId;
  });

  afterAll(async () => {
    try { await client.query('SET search_path TO public'); } catch { /* ignore */ }
    try { await client.query(`DROP SCHEMA ${schema} CASCADE`); } catch { /* ignore */ }
    // Clean up public stub tables created during this run (best-effort).
    try {
      await client.query('DROP TABLE IF EXISTS public.project_order_projects CASCADE');
      await client.query('DROP TABLE IF EXISTS public.project_projects CASCADE');
    } catch { /* ignore */ }
    await client.end();
  });

  // -----------------------------------------------------------------------
  // FINDING 1 — flag-ON listOrders GROUP BY SQL must not throw
  // -----------------------------------------------------------------------
  it('flag-ON: listOrders executes without SQL error (GROUP BY regression catch)', async () => {
    // sheetOrdersReads=true is the flag-ON state.
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const result = await repo.listOrders(minimalListCommand());
    expect(result).toBeDefined();
    expect(result.data).toBeInstanceOf(Array);
    // Our seeded order should be in the results.
    expect(result.data.length).toBeGreaterThan(0);
  });

  it('flag-OFF: listOrders executes without SQL error (legacy path)', async () => {
    // sheetOrdersReads=false is the flag-OFF (legacy) state.
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, false);
    const result = await repo.listOrders(minimalListCommand());
    expect(result).toBeDefined();
    expect(result.data).toBeInstanceOf(Array);
  });

  it('flag-ON: listOrders returns sheetMaterialTypeIds populated and materialIds empty', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const result = await repo.listOrders(minimalListCommand());

    // Find our VB read-repo test order.
    const item = result.data.find((o) => o.orderId === Number(orderId));
    expect(item).toBeDefined();
    if (!item) return;

    // post-034: material_id is NULL → materialIds array should be empty.
    expect(item.materialIds).toEqual([]);
    // sheet_material_type_id is authoritative → sheetMaterialTypeIds should have smtId.
    expect(item.sheetMaterialTypeIds).toContain(Number(smtId));
  });

  // -----------------------------------------------------------------------
  // FINDING 2 — flag-ON getOrderById must preserve header milling/edge/film refs
  // -----------------------------------------------------------------------
  it('flag-ON: getOrderById executes without SQL error', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
  });

  it('flag-OFF: getOrderById executes without SQL error (legacy path)', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, false);
    // Use the legacy-seeded order from seedVariantAMain (order_id=1).
    const order = await repo.getOrderById(getByIdCommand(1));
    expect(order).not.toBeNull();
  });

  it('flag-ON: getOrderById preserves milling_type_id in header', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
    // milling_type_id=1 was set on the order; must survive backend read.
    expect(order!.header.millingTypeId).toBe(1);
  });

  it('flag-ON: getOrderById preserves edge_type_id in header', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
    // edge_type_id=1 was set on the order; must survive backend read.
    expect(order!.header.edgeTypeId).toBe(1);
  });

  it('flag-ON: getOrderById preserves film_id in header', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
    // film_id=1 was set on the order; must survive backend read.
    expect(order!.header.filmId).toBe(1);
  });

  it('flag-ON: getOrderById returns materialId=null in header (Variant B contract)', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
    // Variant B: order.material_id is NULL post-034 (material_id sunset).
    expect(order!.header.materialId).toBeNull();
  });

  it('flag-ON: getOrderById detail has materialId=null and sheetMaterialTypeId set', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, true);
    const order = await repo.getOrderById(getByIdCommand(orderId));
    expect(order).not.toBeNull();
    const detail = order!.details[0];
    expect(detail).toBeDefined();
    // Variant B: material_id is NULL on detail.
    expect(detail.materialId).toBeNull();
    // sheet_material_type_id is authoritative.
    expect(detail.sheetMaterialTypeId).toBe(Number(smtId));
  });

  it('flag-OFF: getOrderById returns basic data (legacy path sanity)', async () => {
    const db = makeDbClient(client, schema);
    const repo = new PgOrderReadRepository(db, false);
    // The legacy-seeded order (order_id=1) from seedVariantAMain
    const order = await repo.getOrderById(getByIdCommand(1));
    expect(order).not.toBeNull();
    expect(order!.header.orderId).toBe(1);
  });
});

