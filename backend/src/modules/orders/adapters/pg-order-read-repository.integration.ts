function mig(n: string): string {
  return readFileSync(join(__dirname, '../../../../db/migrations', n), 'utf8');
}

// Wraps a pg.Client into the DatabaseClient interface expected by PgOrderReadRepository.
function makeDbClient(client: Client, schema: string): DatabaseClient {
  return {
    async query<T extends QueryResultRow = QueryResultRow>(
      text: string,
      params?: readonly unknown[],
    ): Promise<QueryResult<T>> {
      // Ensure each query runs with the correct search_path (the schema can be shared
      // across tests in a suite that re-uses the same Client, so we always set it).
      await client.query(`SET search_path TO ${schema}, public`);
      return client.query<T>(text, params as unknown[]);
    },
  };
}

function minimalListCommand() {
  return {
    currentUser: { id: '1', username: 'admin', role: 'admin', permissions: [] } as never,
    query: {
      page: 1,
      pageSize: 20,
      sortBy: 'orderId' as const,
      sortOrder: 'desc' as const,
      onlyMyOrders: false,
    },
  };
}

function getByIdCommand(orderId: number) {
  return {
    currentUser: { id: '1', username: 'admin', role: 'admin', permissions: [] } as never,
    orderId,
  };
}

