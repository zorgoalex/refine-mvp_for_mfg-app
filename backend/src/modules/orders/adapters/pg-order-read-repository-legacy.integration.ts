// "flag-OFF" tests on POST-034 data (material_id already NULL), so they only proved
// "no throw / not null" — not that the legacy SQL paths produce correct output.
//
// THIS file fixes that by building a dedicated isolated schema that applies migrations
// 029 + 030 + 033 (the Variant B pre-requisites) but NOT 034, then seeds LEGACY data
// (order_details.material_id POPULATED, real materials rows with material_name, and
// SP2-linked sheet types for context) and asserts REAL legacy outputs:
//   - detail.materialId is populated (non-null, matching seeded id)
//   - detail.materialName resolves from the materials catalog (legacy JOIN path)
//   - listOrders aggregate materialIds is non-empty and contains the seeded material id
//   - listOrders aggregate materialNames contains the seeded material_name
//   - sheetMaterialTypeIds is null/empty (flag-OFF produces NULL::bigint[])
//   - header.materialId (getOrderById) is populated (legacy o.material_id path)
//
// ISOLATION: runs inside a dedicated schema (vb_legacy_read_<hrtime>) — mirrors the
// approach in migration-034-rollback.integration.ts. Drop in afterAll.
