/** Helper: creates + calculates a minimal single-detail fixture job. Returns job metadata needed by Task-4 tests. */
async function createCalculatedFixtureJob(
  repo: PgCutRepository,
  pool: Pool,
): Promise<{ cutJobId: number; groupKey: string; cutGroupId: number; jobVersion: number; someReservedDetailId: number; someReservedItemId: number }> {
  const job = await repo.createJob({ currentUser: currentUser(), dto: { name: 'T4-Fixture', detailIds: [1] }, requestId: 'fix-c' });
  const calculated = await repo.calculate({ currentUser: currentUser(), cutJobId: job.cutJobId, version: job.version, requestId: 'fix-calc' });
  const groupRow = await pool.query<{ group_key: string; cut_group_id: string | number }>(
    'SELECT group_key, cut_group_id FROM cut_group WHERE cut_job_id = $1 LIMIT 1',
    [job.cutJobId],
  );
  const itemRow = await pool.query<{ cut_job_item_id: string | number; order_detail_id: string | number }>(
    'SELECT cut_job_item_id, order_detail_id FROM cut_job_item WHERE cut_job_id = $1 AND is_active = true LIMIT 1',
    [job.cutJobId],
  );
  return {
    cutJobId: job.cutJobId,
    groupKey: groupRow.rows[0].group_key,
    cutGroupId: Number(groupRow.rows[0].cut_group_id),
    jobVersion: calculated.version,
    someReservedDetailId: Number(itemRow.rows[0].order_detail_id),
    someReservedItemId: Number(itemRow.rows[0].cut_job_item_id),
  };
}

