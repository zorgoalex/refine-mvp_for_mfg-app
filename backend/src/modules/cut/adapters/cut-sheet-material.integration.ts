// ── DatabaseService wrapper ───────────────────────────────────────────────────

function makeDatabase(pool: Pool): DatabaseService {
  const query = (text: string, params: readonly unknown[] = []) =>
    pool.query(text, [...params]);
  return {
    isConfigured: true,
    query,
    async transaction<T>(handler: (client: TransactionClient) => Promise<T>): Promise<T> {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        await client.query(`SET search_path TO ${schemaName}`);
        const tx: TransactionClient = {
          raw: client as never,
          query: (text: string, params: readonly unknown[] = []) =>
            client.query(text, [...params]),
        };
        const result = await handler(tx);
        await client.query('COMMIT');
        return result;
      } catch (error) {
        await client.query('ROLLBACK').catch(() => undefined);
        throw error;
      } finally {
        client.release();
      }
    },
  } as unknown as DatabaseService;
}

// ── FreecutClient stub ────────────────────────────────────────────────────────
//
// Echo optimizer: returns every item placed on the first (and only) stock from
// the request. Mirrors the echo pattern used in pg-cut-repository.integration.ts
// so the calculate path reaches 'ready' in the test environment.

type FreecutRequest = {
  stock: Array<{ id: string; width_mm: number; height_mm: number }>;
  items: Array<{ id: string; width_mm: number; height_mm: number }>;
};

function makeEchoFreecut() {
  return {
    optimize: (req: FreecutRequest): Promise<FreecutOptimizeResponse> =>
      Promise.resolve({
        status: 'ok',
        summary: { used_stock_count: 1, waste_percent: 5 },
        solutions: [
          {
            stock_id: req.stock[0].id,
            index: 0,
            width_mm: req.stock[0].width_mm,
            height_mm: req.stock[0].height_mm,
            trim_mm: { left: 10, right: 10, top: 10, bottom: 10 },
            placements: req.items.map((it, i) => ({
              item_id: it.id,
              instance: 1,
              x_mm: i * 620,
              y_mm: 0,
              width_mm: it.width_mm,
              height_mm: it.height_mm,
              rotated: false,
            })),
          },
        ],
      }),
  };
}

