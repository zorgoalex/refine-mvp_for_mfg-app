/**
 * cut-sheet-material.integration.ts
 *
 * Real-DB integration test for the per-job sheet-material override (migration 040).
 *
 * Gated by CUT_INTEGRATION_DATABASE_URL or TEST_DATABASE_URL. When neither is
 * set all tests are skipped (describe.skip). The orchestrator runs this against
 * erp_test using the .env secret.
 *
 * Collected by vitest.cut-integration.config.ts via:
 *   include: ['backend/src/modules/cut/adapters/*.integration.ts']
 *
 * What it verifies (5 scenarios from the task-9 brief):
 *   1. setSheetMaterial to a cuttable sheet → DB column set, version bumped,
 *      exactly one audit_log row (cut_job.sheet_material_changed) with
 *      sheetMaterialTypeIds bridge rows, exactly one outbox_events row;
 *      replay same requestId → no duplicate outbox row (idempotent).
 *   2. setSheetMaterial to a non-cuttable (is_cuttable=false) sheet → 422
 *      CUT_SHEET_MATERIAL_NOT_CUTTABLE, no mutation.
 *   3. calculate with override set on a job whose details span TWO materials
 *      AND include one no_sheet_spec detail → all groups use the chosen sheet;
 *      the no_sheet_spec detail is placed; job reaches 'ready'.
 *   4. calculate after the chosen sheet is deactivated → 422
 *      CUT_SHEET_MATERIAL_NOT_CUTTABLE, job NOT marked 'failed' (status
 *      unchanged from pre-calculate).
 *   5. Override = NULL → unchanged legacy behavior (per-detail sheet; a
 *      no_sheet_spec detail still yields CutNoSheetSpecError).
 */
