import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { Pool, type PoolClient } from 'pg';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import type { DatabaseService } from '../../../database/database.service';
import type { CurrentUser } from '../../../permissions/current-user';
import { PgCutRepository } from './pg-cut-repository';

const databaseUrl = process.env.CUT_RESULT_HISTORY_TEST_DATABASE_URL
  ?? process.env.CUT_INTEGRATION_DATABASE_URL
  ?? process.env.TEST_DATABASE_URL;
const describeIntegration = databaseUrl ? describe : describe.skip;
const schema = `cut_result_history_${randomUUID().replaceAll('-', '_')}`;
const migration079 = readFileSync(new URL('../../../../db/migrations/079_cut_result_history_expand.sql', import.meta.url), 'utf8');
const migration080 = readFileSync(new URL('../../../../db/migrations/080_cut_result_history_finalize.sql', import.meta.url), 'utf8');
const migration085 = readFileSync(new URL('../../../../db/migrations/085_cut_result_manual_revisions.sql', import.meta.url), 'utf8');

function renderSnapshot() {
  return {
    contractVersion: 'cut_sheet_render_v1',
    views: Object.fromEntries(Array.from({ length: 12 }, (_, index) => [`view-${index}`, { svg: '<svg/>', bathSvg: '<svg/>' }])),
    pdfMeta: {},
    pdfDetailRows: [],
  };
}

function validSnapshot() {
  return {
    cutJobId: 1,
    version: 1,
    items: [{ orderDetailId: 10, qty: 1, cutGroupId: 20 }],
    groups: [{
      cutGroupId: 20,
      sheets: [{
        sheetIndex: 0,
        placements: { pieces: [{ item_id: 'det-10', instance: 1 }] },
        renderSnapshot: renderSnapshot(),
      }],
      manualLayout: null as null | {
        sheets: Array<{ sheetIndex: number; placements: { pieces: Array<{ item_id: string; instance: number }> }; renderSnapshot: ReturnType<typeof renderSnapshot> }>;
        isActive: boolean;
        isStale: boolean;
      },
    }],
    totals: { positions: 1, details: 1, area: 0, sheets: 1 },
    unplaced: [],
  };
}

function manifest(snapshot = validSnapshot()) {
  return {
    groups: snapshot.groups.length,
    items: snapshot.items.length,
    instances: snapshot.items.reduce((sum, item) => sum + item.qty, 0),
    unplaced: Array.isArray(snapshot.unplaced) ? snapshot.unplaced.length : 0,
    variants: snapshot.groups.map((group) => ({
      groupKey: `group:${group.cutGroupId}`,
      autoSheets: group.sheets.map((sheet) => sheet.sheetIndex),
      manualSheets: group.manualLayout?.sheets.map((sheet) => sheet.sheetIndex) ?? [],
      renderContract: 'cut_sheet_render_v1',
      autoRenderViews: group.sheets.map((sheet) => Object.keys(sheet.renderSnapshot.views).length),
      manualRenderViews: group.manualLayout?.sheets.map((sheet) => Object.keys(sheet.renderSnapshot.views).length) ?? [],
      manualState: group.manualLayout
        ? group.manualLayout.isStale ? 'stale' : group.manualLayout.isActive ? 'active' : 'inactive'
        : 'none',
    })),
  };
}

describeIntegration('cut result history migration chain including manual revisions', () => {
  const pool = new Pool({ connectionString: databaseUrl });
  let client: PoolClient;
  let finalizeRejectedPartial = false;

  function snapshotWithManualState(state: 'active' | 'inactive' | 'stale') {
    const snapshot = validSnapshot();
    snapshot.groups[0].manualLayout = {
      sheets: [{
        sheetIndex: 0,
        placements: { pieces: [{ item_id: 'det-10', instance: 1 }] },
        renderSnapshot: renderSnapshot(),
      }],
      isActive: state === 'active',
      isStale: state === 'stale',
    };
    return snapshot;
  }

  beforeAll(async () => {
    client = await pool.connect();
    await client.query(`CREATE SCHEMA ${schema}`);
    await client.query(`SET search_path TO ${schema}, public`);
    await client.query(`
      CREATE TABLE users (user_id BIGINT PRIMARY KEY, username TEXT);
      CREATE TABLE cut_job (
        cut_job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        current_cut_result_id BIGINT,
        next_cut_result_no INTEGER NOT NULL DEFAULT 1
      );
    `);
    await client.query(migration079);

    const partialJob = await createJob();
    await client.query(
      `INSERT INTO ${schema}.cut_result
         (cut_job_id, result_no, result_kind, source_job_version)
       VALUES ($1, 1, 'legacy', 1)`,
      [partialJob],
    );
    try {
      await client.query(migration080);
    } catch {
      finalizeRejectedPartial = true;
      await client.query('ROLLBACK');
    }
    await client.query(`DELETE FROM ${schema}.cut_result WHERE cut_job_id = $1`, [partialJob]);

    await insertLegacy(validSnapshot());
    await insertLegacy(snapshotWithManualState('active'));
    await insertLegacy(snapshotWithManualState('inactive'));
    await insertLegacy(snapshotWithManualState('stale'));
    await client.query(migration080);
    await client.query(migration085);
  });

  afterAll(async () => {
    if (client) {
      await client.query('SET search_path TO public');
      await client.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      client.release();
    }
    await pool.end();
  });

  async function createJob(): Promise<number> {
    const row = await client.query<{ cut_job_id: string }>(
      `INSERT INTO ${schema}.cut_job (name) VALUES ('test') RETURNING cut_job_id`,
    );
    return Number(row.rows[0].cut_job_id);
  }

  async function insertLegacy(snapshot: ReturnType<typeof validSnapshot>, digestSql = 'cut_result_snapshot_digest($4::jsonb)') {
    const cutJobId = await createJob();
    const snapshotForJob = { ...snapshot, cutJobId };
    return client.query(
      `INSERT INTO ${schema}.cut_result
         (cut_job_id, result_no, result_kind, source_job_version,
          snapshot_job, snapshot_manifest, snapshot_digest, totals_snapshot)
       VALUES ($1, 1, 'legacy', 1, $2::jsonb, $3::jsonb, ${digestSql}, $5::jsonb)
       RETURNING cut_result_id`,
      [cutJobId, JSON.stringify(snapshotForJob), JSON.stringify(manifest(snapshotForJob)), JSON.stringify(snapshotForJob), JSON.stringify(snapshotForJob.totals)],
    );
  }

  it('accepts a complete snapshot and enforces append-only rows', async () => {
    const inserted = await insertLegacy(validSnapshot());
    await expect(client.query(
      `UPDATE ${schema}.cut_result SET result_no = 2 WHERE cut_result_id = $1`,
      [inserted.rows[0].cut_result_id],
    )).rejects.toThrow(/append-only/i);
  });

  it('accepts immutable revisions under one public result number', async () => {
    const cutJobId = await createJob();
    const snapshot = { ...validSnapshot(), cutJobId };
    const params = [
      cutJobId,
      JSON.stringify(snapshot),
      JSON.stringify(manifest(snapshot)),
      JSON.stringify(snapshot.totals),
    ];
    await client.query(
      `INSERT INTO ${schema}.cut_result
         (cut_job_id, result_no, revision_no, result_kind, source_job_version,
          snapshot_job, snapshot_manifest, snapshot_digest, totals_snapshot)
       VALUES ($1, 1, 1, 'legacy', 1, $2::jsonb, $3::jsonb,
               cut_result_snapshot_digest($2::jsonb), $4::jsonb)`,
      params,
    );
    const latest = await client.query<{ cut_result_id: string }>(
      `INSERT INTO ${schema}.cut_result
         (cut_job_id, result_no, revision_no, result_kind, source_job_version,
          snapshot_job, snapshot_manifest, snapshot_digest, totals_snapshot)
       VALUES ($1, 1, 2, 'legacy', 2, $2::jsonb, $3::jsonb,
               cut_result_snapshot_digest($2::jsonb), $4::jsonb)
       RETURNING cut_result_id`,
      params,
    );
    await client.query(
      `UPDATE ${schema}.cut_job
       SET current_cut_result_id = $2, next_cut_result_no = 2
       WHERE cut_job_id = $1`,
      [cutJobId, latest.rows[0].cut_result_id],
    );
    const rows = await client.query<{ n: number }>(
      `SELECT count(*)::int AS n
       FROM ${schema}.cut_result
       WHERE cut_job_id = $1 AND result_no = 1`,
      [cutJobId],
    );
    expect(rows.rows[0].n).toBe(2);

    const database = {
      isConfigured: true,
      query: (text: string, values: readonly unknown[] = []) => client.query(text, [...values]),
    } as unknown as DatabaseService;
    const repo = new PgCutRepository(database, {
      optimize: async () => { throw new Error('optimizer must not run while reading history'); },
    });
    const currentUser = {
      id: '1',
      username: 'tester',
      role: 'operator',
      permissions: ['cut.view'],
    } as unknown as CurrentUser;
    const listed = await repo.listResults({ currentUser, cutJobId });
    expect(listed).toHaveLength(1);
    expect(listed[0]).toMatchObject({
      cutResultId: Number(latest.rows[0].cut_result_id),
      resultNo: 1,
      sourceJobVersion: 2,
      isCurrent: true,
    });
    const opened = await repo.getResult({ currentUser, cutJobId, resultNo: 1 });
    expect(opened.cutResultId).toBe(Number(latest.rows[0].cut_result_id));
  });

  it('blocks finalize over a partial expand row, then accepts all legacy manual states', async () => {
    expect(finalizeRejectedPartial).toBe(true);
    const rows = await client.query<{ n: number }>(
      `SELECT count(*)::int AS n FROM ${schema}.cut_result WHERE result_kind = 'legacy'`,
    );
    expect(rows.rows[0].n).toBeGreaterThanOrEqual(4);
  });

  it('rejects missing keys, a forged digest, and placed/unplaced count corruption', async () => {
    const missingUnplaced = validSnapshot() as ReturnType<typeof validSnapshot> & { unplaced?: unknown[] };
    delete missingUnplaced.unplaced;
    await expect(insertLegacy(missingUnplaced as ReturnType<typeof validSnapshot>)).rejects.toThrow();

    await expect(insertLegacy(validSnapshot(), "repeat('0', 64) || substring($4::text, 1, 0)")).rejects.toThrow();

    const duplicate = validSnapshot();
    duplicate.groups[0].sheets[0].placements.pieces.push({ item_id: 'det-10', instance: 1 });
    await expect(insertLegacy(duplicate)).rejects.toThrow();
  });

  it('rejects a manual variant with a different piece set', async () => {
    const snapshot = validSnapshot();
    snapshot.groups[0].manualLayout = {
      sheets: [{ sheetIndex: 0, placements: { pieces: [] }, renderSnapshot: renderSnapshot() }],
      isActive: true,
      isStale: false,
    } as never;
    await expect(insertLegacy(snapshot)).rejects.toThrow();
  });

  it('enforces the deferred result↔ledger link and terminal command immutability', async () => {
    const cutJobId = await createJob();
    const commandId = randomUUID();
    const payloadHash = 'payload-hash';
    const snapshot = { ...validSnapshot(), cutJobId };
    await client.query('BEGIN');
    try {
      await client.query(
        `INSERT INTO ${schema}.cut_result_command
           (cut_job_id, command_id, command_type, payload_hash, status,
            owner_token, lease_expires_at, heartbeat_at, claimed_job_version)
         VALUES ($1, $2, 'calculate', $3, 'in_progress', $4, now() + interval '1 minute', now(), 1)`,
        [cutJobId, commandId, payloadHash, randomUUID()],
      );
      const result = await client.query<{ cut_result_id: string }>(
        `INSERT INTO ${schema}.cut_result
           (cut_job_id, result_no, result_kind, source_job_version,
            command_id, command_payload_hash, snapshot_job, snapshot_manifest,
            snapshot_digest, totals_snapshot)
         VALUES ($1, 1, 'auto', 1, $2, $3, $4::jsonb, $5::jsonb,
                 cut_result_snapshot_digest($4::jsonb), $6::jsonb)
         RETURNING cut_result_id`,
        [cutJobId, commandId, payloadHash, JSON.stringify(snapshot), JSON.stringify(manifest(snapshot)), JSON.stringify(snapshot.totals)],
      );
      await client.query(
        `UPDATE ${schema}.cut_result_command
         SET status = 'completed', cut_result_id = $3, owner_token = NULL,
             lease_expires_at = NULL, completed_at = now()
         WHERE cut_job_id = $1 AND command_id = $2`,
        [cutJobId, commandId, result.rows[0].cut_result_id],
      );
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    }

    await expect(client.query(
      `UPDATE ${schema}.cut_result_command SET heartbeat_at = now()
       WHERE cut_job_id = $1 AND command_id = $2`,
      [cutJobId, commandId],
    )).rejects.toThrow(/terminal.*immutable/i);

    await client.query('BEGIN');
    await client.query(
      `INSERT INTO ${schema}.cut_result_command
         (cut_job_id, command_id, command_type, payload_hash, status, completed_at)
       VALUES ($1, $2, 'manual_save', 'bad-terminal', 'completed', now())`,
      [cutJobId, randomUUID()],
    );
    await expect(client.query('COMMIT')).rejects.toThrow(/invalid completed/i);
    await client.query('ROLLBACK');
  });
});
