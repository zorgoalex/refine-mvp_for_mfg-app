// ── Test suite ────────────────────────────────────────────────────────────────

describeIntegration('CRM sync pipeline end-to-end (integration)', () => {
  let pool: Pool;
  let db: DatabaseService;
  let outboxRepo: PgCrmSyncOutboxRepository;
  let mappingRepo: PgCrmSyncMappingRepository;
  let stub: StubTwentyApiClient;
  let relay: CrmSyncRelayService;

  beforeAll(async () => {
    pool = new Pool({ connectionString: databaseUrl, max: 4 });

    // Create schema first (dedicated client, before pool.on)
    const setupClient = await pool.connect();
    try {
      await setupClient.query(`CREATE SCHEMA ${schemaName}`);
      await setupClient.query(`SET search_path TO ${schemaName}`);
    } finally {
      setupClient.release();
    }

    // Pin search_path for ALL future pooled connections
    pool.on('connect', (c) => void c.query(`SET search_path TO ${schemaName}`));

    // Bootstrap schema tables and triggers
    await bootstrapSchema(pool);

    // Wire up services
    db = makeDatabase(pool);
    outboxRepo = new PgCrmSyncOutboxRepository();
    mappingRepo = new PgCrmSyncMappingRepository();
    const sourceRepo = new PgCrmSourceRepository(db);
    stub = new StubTwentyApiClient();
    const audit = new AuditService();
    const config = makeConfig();

    const consumer = new TwentySyncConsumer({
      source: sourceRepo,
      twenty: stub,
      mapping: mappingRepo,
      db,
    });

    const dryRunConsumer = new TwentySyncConsumer({
      source: sourceRepo,
      twenty: stub,
      mapping: mappingRepo,
      db,
    });

    relay = new CrmSyncRelayService({
      outboxRepo,
      consumer,
      dryRunConsumer,
      mapping: mappingRepo,
      audit,
      db,
      config,
    });
  });

  afterAll(async () => {
    if (pool) {
      await pool.query(`DROP SCHEMA IF EXISTS ${schemaName} CASCADE`);
      await pool.end();
    }
  });

  // ── Scenario 1: INSERT client → one pending outbox row ───────────────────

  let insertedClientId: string;

  it('SC-1: INSERT client fires trigger → exactly ONE pending crm_sync_outbox row', async () => {
    const res = await pool.query<{ client_id: string }>(
      `INSERT INTO ${schemaName}.clients (client_name, notes, is_active)
       VALUES ('Тест Компания А', 'Тестовые заметки', true)
       RETURNING client_id`,
    );
    insertedClientId = String(res.rows[0].client_id);

    const outbox = await pool.query<{ count: string; aggregate_id: string; status: string }>(
      `SELECT COUNT(*)::text AS count, aggregate_id, status
         FROM ${schemaName}.crm_sync_outbox
        WHERE aggregate_id = $1
        GROUP BY aggregate_id, status`,
      [insertedClientId],
    );
    expect(outbox.rows).toHaveLength(1);
    expect(outbox.rows[0].count).toBe('1');
    expect(outbox.rows[0].status).toBe('pending');
  });

  // ── Scenario 2: runTick → mapping.twenty_id set, audit_log NOT NULL request_id, outbox='processed' ─

  it('SC-2: relay.runTick() → mapping.twenty_id set, audit_log.request_id NOT NULL, outbox=processed', async () => {
    const result = await relay.runTick();
    expect(result.claimed).toBeGreaterThanOrEqual(1);
    expect(result.processed).toBeGreaterThanOrEqual(1);
    expect(result.failed).toBe(0);

    // Mapping should now have a twenty_id
    const mapping = await pool.query<{
      entity_type: string;
      twenty_id: string | null;
      status: string;
    }>(
      `SELECT entity_type, twenty_id, status
         FROM ${schemaName}.crm_sync_mapping
        WHERE entity_type = 'client' AND erp_id = $1`,
      [insertedClientId],
    );
    expect(mapping.rows).toHaveLength(1);
    expect(mapping.rows[0].twenty_id).toBeTruthy();
    expect(mapping.rows[0].status).toBe('active');

    // Outbox row should be 'processed'
    const outbox = await pool.query<{ status: string }>(
      `SELECT status FROM ${schemaName}.crm_sync_outbox WHERE aggregate_id = $1 ORDER BY created_at DESC LIMIT 1`,
      [insertedClientId],
    );
    expect(outbox.rows[0]?.status).toBe('processed');

    // audit_log must have a row with non-null request_id (proves NOT NULL contract)
    const audit = await pool.query<{ request_id: string | null; source: string }>(
      `SELECT request_id, source
         FROM ${schemaName}.audit_log
        WHERE entity_type = 'client' AND entity_id = $1
        ORDER BY created_at DESC
        LIMIT 1`,
      [insertedClientId],
    );
    expect(audit.rows).toHaveLength(1);
    expect(audit.rows[0].request_id).not.toBeNull();
    expect(audit.rows[0].request_id).toBeTruthy();
    expect(audit.rows[0].source).toBe('crm-sync');
  });

  // ── Scenario 3: UPDATE is_active=false → tick → mapping.status='deleted' ─

  it('SC-3: UPDATE clients SET is_active=false → tick → mapping.status=deleted', async () => {
    stub.setThrow(false);
    const beforeCreateCalls = stub.createCalls;

    await pool.query(
      `UPDATE ${schemaName}.clients SET is_active = false WHERE client_id = $1`,
      [insertedClientId],
    );

    // Trigger should have produced a new pending outbox row
    const pending = await pool.query<{ count: string }>(
      `SELECT COUNT(*)::text AS count FROM ${schemaName}.crm_sync_outbox
        WHERE aggregate_id = $1 AND status = 'pending'`,
      [insertedClientId],
    );
    expect(Number(pending.rows[0].count)).toBeGreaterThanOrEqual(1);

    const result = await relay.runTick();
    expect(result.processed).toBeGreaterThanOrEqual(1);
    expect(result.failed).toBe(0);

    // isActive=false → erpStatusFor(!isActive)=erpStatusFor(true)='deleted'
    const mapping = await pool.query<{ status: string; twenty_id: string }>(
      `SELECT status, twenty_id FROM ${schemaName}.crm_sync_mapping
        WHERE entity_type = 'client' AND erp_id = $1`,
      [insertedClientId],
    );
    expect(mapping.rows[0].status).toBe('deleted');

    // Stub Company record must have received erpStatus='deleted'
    const stubCompany = stub.records.get(mapping.rows[0].twenty_id);
    expect(stubCompany?.erpStatus).toBe('deleted');

    // No new create — existing twenty_id reused via updateRecord
    expect(stub.createCalls).toBe(beforeCreateCalls);
    expect(mapping.rows[0].twenty_id).toBeTruthy();
  });

  // ── Scenario 4: Re-run same upsert → no duplicate create (idempotency) ───

  it('SC-4: re-processing same client does NOT call createRecord again (hash no-op)', async () => {
    const beforeCreate = stub.createCalls;

    // Force a new pending outbox row (simulating a re-trigger with a unique idempotency key)
    await pool.query(
      `INSERT INTO ${schemaName}.crm_sync_outbox
         (event_type, aggregate_type, aggregate_id, payload_json, idempotency_key, next_attempt_at)
       VALUES ('crm.sync.client.upsert', 'crm_sync', $1,
               jsonb_build_object('entity', 'client', 'id', $1, 'op', 'upsert'),
               $2, now() - interval '1 second')`,
      [insertedClientId, `client:${insertedClientId}:rerun-${randomUUID()}`],
    );

    const result = await relay.runTick();
    // Consumer detects hash match (already synced, same body hash) → returns []
    // The relay processes the event but no new create is called
    expect(stub.createCalls).toBe(beforeCreate);
    expect(result.failed).toBe(0);
    expect(result.processed).toBeGreaterThanOrEqual(1);
  });

  // ── Scenario 5: Forced Twenty error → mapping.status='failed' ────────────

  it('SC-5: Twenty API throws → tick marks outbox+mapping as failed', async () => {
    const res = await pool.query<{ client_id: string }>(
      `INSERT INTO ${schemaName}.clients (client_name, is_active)
       VALUES ('Тест Компания Б', true)
       RETURNING client_id`,
    );
    const failClientId = String(res.rows[0].client_id);

    // Pre-bump attempts to maxAttempts-1 (=2) so next markRetry → attempts+1=3 >= 3 → status=failed
    await pool.query(
      `UPDATE ${schemaName}.crm_sync_outbox SET attempts = 2
        WHERE aggregate_id = $1 AND status = 'pending'`,
      [failClientId],
    );

    stub.setThrow(true);
    const result = await relay.runTick();
    stub.setThrow(false);

    expect(result.failed).toBeGreaterThanOrEqual(1);

    // Mapping should be 'failed'
    const mapping = await pool.query<{ status: string; last_error: string | null }>(
      `SELECT status, last_error FROM ${schemaName}.crm_sync_mapping
        WHERE entity_type = 'client' AND erp_id = $1`,
      [failClientId],
    );
    expect(mapping.rows).toHaveLength(1);
    expect(mapping.rows[0].status).toBe('failed');
    expect(mapping.rows[0].last_error).toBeTruthy();
  });

  // ── Scenario 6: Coalescing — two rapid UPDATEs → ONE pending outbox row ──

  it('SC-6: two rapid UPDATEs coalesce to ONE pending outbox row', async () => {
    const res = await pool.query<{ client_id: string }>(
      `INSERT INTO ${schemaName}.clients (client_name, is_active)
       VALUES ('Тест Компания В', true)
       RETURNING client_id`,
    );
    const coalesceClientId = String(res.rows[0].client_id);

    // Process the initial insert outbox event so we start clean
    await relay.runTick();

    // Two rapid UPDATEs — trigger coalesces (DELETE pending + INSERT fresh)
    await pool.query(
      `UPDATE ${schemaName}.clients SET notes = 'Первое обновление' WHERE client_id = $1`,
      [coalesceClientId],
    );
    await pool.query(
      `UPDATE ${schemaName}.clients SET notes = 'Второе обновление' WHERE client_id = $1`,
      [coalesceClientId],
    );

    const pending = await pool.query<{ count: string }>(
      `SELECT COUNT(*)::text AS count
         FROM ${schemaName}.crm_sync_outbox
        WHERE aggregate_id = $1 AND status = 'pending'`,
      [coalesceClientId],
    );
    // Trigger coalesces: DELETE old pending then INSERT new → exactly 1 pending row
    expect(pending.rows[0].count).toBe('1');
  });
});
