// ── Throwaway schema name (unique per run) ────────────────────────────────────
const schemaName = `crm_e2e_${randomUUID().replaceAll('-', '_')}`;

// ── Schema bootstrap ──────────────────────────────────────────────────────────
// Applies:
//  1. Minimal base tables: order_statuses, payment_statuses, clients, orders
//  2. Real audit_log schema from migrations 001, 004, 012, 017, 020
//     (NOT NULL request_id is the critical contract under test)
//  3. Full migration 025: crm_sync_mapping, crm_sync_outbox, triggers, functions

async function bootstrapSchema(pool: Pool): Promise<void> {
  // ── 1. Minimal base tables ────────────────────────────────────────────────
  await pool.query(`
    CREATE TABLE ${schemaName}.order_statuses (
      order_status_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_status_name TEXT NOT NULL
    );

    CREATE TABLE ${schemaName}.payment_statuses (
      payment_status_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      payment_status_name TEXT NOT NULL
    );

    CREATE TABLE ${schemaName}.clients (
      client_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      client_name TEXT NOT NULL,
      notes TEXT,
      is_active BOOLEAN NOT NULL DEFAULT true
    );

    CREATE TABLE ${schemaName}.orders (
      order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_name TEXT NOT NULL,
      client_id BIGINT NOT NULL REFERENCES ${schemaName}.clients(client_id),
      total_amount NUMERIC(12,2),
      final_amount NUMERIC(12,2),
      paid_amount NUMERIC(12,2),
      order_date DATE,
      completion_date DATE,
      delete_flag BOOLEAN NOT NULL DEFAULT false,
      order_status_id SMALLINT REFERENCES ${schemaName}.order_statuses(order_status_id),
      payment_status_id SMALLINT REFERENCES ${schemaName}.payment_statuses(payment_status_id)
    );
  `);

  // ── 2. audit_log from migrations 001 + 004 + 012 + 017 + 020 ────────────
  // Migration 001: CREATE TABLE audit_log (with NOT NULL request_id)
  await pool.query(`
    CREATE TABLE ${schemaName}.audit_log (
      audit_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      event TEXT NOT NULL,
      action TEXT GENERATED ALWAYS AS (event) STORED,
      entity_type TEXT,
      entity_id TEXT,
      user_id BIGINT,
      username TEXT,
      role_code TEXT,
      role TEXT,
      request_id TEXT NOT NULL,
      ip_address INET,
      user_agent TEXT,
      before_json JSONB,
      after_json JSONB,
      diff_json JSONB,
      metadata_json JSONB,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    );
  `);

  // Migration 004: ALTER TABLE audit_log ADD COLUMN source, related_order_id, etc.
  await pool.query(`
    ALTER TABLE ${schemaName}.audit_log
      ADD COLUMN source TEXT,
      ADD COLUMN related_order_id BIGINT,
      ADD COLUMN related_client_id BIGINT,
      ADD COLUMN related_production_event_id BIGINT,
      ADD COLUMN status_field TEXT,
      ADD COLUMN status_id BIGINT,
      ADD COLUMN status_name TEXT,
      ADD COLUMN status_code TEXT,
      ADD COLUMN stage_code TEXT;
  `);

  // Migration 012: ADD COLUMN related_payment_id, related_deadline_id
  await pool.query(`
    ALTER TABLE ${schemaName}.audit_log
      ADD COLUMN related_payment_id BIGINT,
      ADD COLUMN related_deadline_id BIGINT;
  `);

  // Migration 017: ADD COLUMN related_user_id
  await pool.query(`
    ALTER TABLE ${schemaName}.audit_log
      ADD COLUMN related_user_id BIGINT;
  `);

  // Migration 020: audit_log_related_entity bridge table
  await pool.query(`
    CREATE TABLE ${schemaName}.audit_log_related_entity (
      audit_id    UUID NOT NULL REFERENCES ${schemaName}.audit_log(audit_id) ON DELETE CASCADE,
      entity_type TEXT NOT NULL,
      entity_id   BIGINT NOT NULL,
      PRIMARY KEY (audit_id, entity_type, entity_id)
    );
  `);

  // ── 3. Migration 025: crm_sync_mapping, crm_sync_outbox, trigger function ─
  await pool.query(`
    CREATE TABLE ${schemaName}.crm_sync_mapping (
      entity_type   TEXT NOT NULL CHECK (entity_type IN ('client','order')),
      erp_id        TEXT NOT NULL,
      twenty_object TEXT NOT NULL,
      twenty_id     TEXT,
      status        TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','deleted','failed')),
      attempts      INTEGER NOT NULL DEFAULT 0,
      last_hash     TEXT,
      last_error    TEXT,
      last_synced_at TIMESTAMPTZ,
      created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
      CONSTRAINT pk_crm_sync_mapping PRIMARY KEY (entity_type, erp_id),
      CONSTRAINT uq_crm_sync_mapping_twenty UNIQUE (entity_type, twenty_id)
    );

    CREATE TABLE ${schemaName}.crm_sync_outbox (
      outbox_event_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      event_type      TEXT NOT NULL,
      aggregate_type  TEXT NOT NULL,
      aggregate_id    TEXT NOT NULL,
      payload_json    JSONB NOT NULL,
      status          TEXT NOT NULL DEFAULT 'pending',
      attempts        INTEGER NOT NULL DEFAULT 0,
      next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      locked_at       TIMESTAMPTZ,
      locked_by       TEXT,
      lock_token      TEXT,
      idempotency_key TEXT,
      created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
      processed_at    TIMESTAMPTZ,
      CONSTRAINT chk_crm_sync_outbox_status CHECK (status IN ('pending','processing','processed','failed'))
    );

    CREATE INDEX idx_crm_outbox_pending_${schemaName.replace(/-/g, '_')}
      ON ${schemaName}.crm_sync_outbox (next_attempt_at, created_at) WHERE status = 'pending';

    CREATE INDEX idx_crm_outbox_key_pending_${schemaName.replace(/-/g, '_')}
      ON ${schemaName}.crm_sync_outbox (idempotency_key) WHERE status = 'pending';
  `);

  // Trigger function scoped to this schema
  await pool.query(`
    CREATE OR REPLACE FUNCTION ${schemaName}.crm_sync_enqueue() RETURNS trigger AS $$
    DECLARE
      v_entity TEXT := TG_ARGV[0];
      v_op TEXT;
      v_id TEXT;
      v_key TEXT;
    BEGIN
      IF TG_OP = 'DELETE' THEN
        v_op := 'delete'; v_id := (CASE v_entity WHEN 'client' THEN OLD.client_id ELSE OLD.order_id END)::text;
      ELSE
        v_op := 'upsert'; v_id := (CASE v_entity WHEN 'client' THEN NEW.client_id ELSE NEW.order_id END)::text;
      END IF;
      v_key := v_entity || ':' || v_id;
      DELETE FROM ${schemaName}.crm_sync_outbox WHERE idempotency_key = v_key AND status = 'pending';
      INSERT INTO ${schemaName}.crm_sync_outbox (event_type, aggregate_type, aggregate_id, payload_json, idempotency_key)
      VALUES ('crm.sync.' || v_entity || '.' || v_op, 'crm_sync', v_id,
              jsonb_build_object('entity', v_entity, 'id', v_id, 'op', v_op), v_key);
      RETURN NULL;
    END;
    $$ LANGUAGE plpgsql;

    CREATE TRIGGER trg_crm_sync_clients
      AFTER INSERT OR UPDATE OR DELETE ON ${schemaName}.clients
      FOR EACH ROW EXECUTE FUNCTION ${schemaName}.crm_sync_enqueue('client');

    CREATE TRIGGER trg_crm_sync_orders
      AFTER INSERT OR UPDATE OR DELETE ON ${schemaName}.orders
      FOR EACH ROW EXECUTE FUNCTION ${schemaName}.crm_sync_enqueue('order');
  `);
}

// ── Stub TwentyApiPort ────────────────────────────────────────────────────────
class StubTwentyApiClient implements TwentyApiPort {
  readonly records: Map<string, Record<string, unknown>> = new Map();
  createCalls = 0;
  updateCalls = 0;
  private shouldThrow = false;

  setThrow(enabled: boolean): void {
    this.shouldThrow = enabled;
  }

  async createRecord(
    object: TwentyObject,
    body: Record<string, unknown>,
  ): Promise<{ id: string }> {
    if (this.shouldThrow) {
      throw new Error('Stub Twenty: simulated API error');
    }
    this.createCalls++;
    const id = `stub-${object}-${randomUUID()}`;
    this.records.set(id, { ...body, object });
    return { id };
  }

  async updateRecord(
    object: TwentyObject,
    id: string,
    body: Record<string, unknown>,
  ): Promise<void> {
    if (this.shouldThrow) {
      throw new Error('Stub Twenty: simulated API error');
    }
    this.updateCalls++;
    const existing = this.records.get(id) ?? {};
    this.records.set(id, { ...existing, ...body, object });
  }

  async findIdByErpId(_object: TwentyObject, _erpId: string): Promise<string | null> {
    return null;
  }

  async deleteRecord(_object: TwentyObject, _id: string): Promise<void> {
    // no-op in stub
  }
}

// ── DatabaseService stub backed by the throwaway-schema pool ─────────────────
function makeDatabase(pool: Pool): DatabaseService {
  const query = <T extends Record<string, unknown>>(
    text: string,
    params: readonly unknown[] = [],
  ) => pool.query<T>(text, [...params]);

  return {
    isConfigured: true,
    query,
    async transaction<T>(handler: (client: TransactionClient) => Promise<T>): Promise<T> {
      const raw = await pool.connect();
      try {
        await raw.query('BEGIN');
        await raw.query(`SET search_path TO ${schemaName}`);
        const tx: TransactionClient = {
          raw: raw as never,
          query: <R extends Record<string, unknown>>(
            text: string,
            params: readonly unknown[] = [],
          ) => raw.query<R>(text, [...params]),
        };
        const result = await handler(tx);
        await raw.query('COMMIT');
        return result;
      } catch (err) {
        await raw.query('ROLLBACK').catch(() => undefined);
        throw err;
      } finally {
        raw.release();
      }
    },
  } as unknown as DatabaseService;
}

